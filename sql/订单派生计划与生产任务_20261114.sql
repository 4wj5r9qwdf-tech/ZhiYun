-- 客户订单派生的物料需求计划与生产任务。业务数据和审批过程分离。
BEGIN;
CREATE TABLE IF NOT EXISTS biz_material_demand_plan (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES biz_customer_order(id),
    order_revision integer NOT NULL,
    plan_no varchar(64) NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','submitted','approved','cancelled')),
    revision integer NOT NULL DEFAULT 1,
    document jsonb NOT NULL,
    workflow_instance_id bigint,
    created_by bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_material_demand_plan_no UNIQUE(plan_no)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_material_demand_plan_active_order ON biz_material_demand_plan(order_id) WHERE status <> 'cancelled';
COMMENT ON TABLE biz_material_demand_plan IS '客户订单派生物料需求计划，保留 BOM、采购单位和库存单位需求快照';
COMMENT ON COLUMN biz_material_demand_plan.order_id IS '来源客户订单';
COMMENT ON COLUMN biz_material_demand_plan.order_revision IS '生成时来源订单版本';
COMMENT ON COLUMN biz_material_demand_plan.plan_no IS '需求计划单号';
COMMENT ON COLUMN biz_material_demand_plan.status IS '单据状态：草稿、审批中、已审核、已取消';
COMMENT ON COLUMN biz_material_demand_plan.revision IS '并发更新版本';
COMMENT ON COLUMN biz_material_demand_plan.document IS '需求来源、库存单位数量、采购单位换算快照及计划调整';
COMMENT ON COLUMN biz_material_demand_plan.workflow_instance_id IS '统一审批流程实例编号';
COMMENT ON COLUMN biz_material_demand_plan.created_by IS '创建人';
COMMENT ON COLUMN biz_material_demand_plan.created_at IS '创建时间';
COMMENT ON COLUMN biz_material_demand_plan.updated_at IS '最近修改时间';
COMMENT ON COLUMN biz_material_demand_plan.id IS '需求计划内部主键';
CREATE TABLE IF NOT EXISTS biz_production_task (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES biz_customer_order(id),
    order_revision integer NOT NULL,
    po_number varchar(100) NOT NULL,
    task_no varchar(64) NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','submitted','approved','cancelled')),
    revision integer NOT NULL DEFAULT 1,
    document jsonb NOT NULL,
    workflow_instance_id bigint,
    created_by bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_production_task_no UNIQUE(task_no)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_production_task_active_po ON biz_production_task(order_id,lower(po_number)) WHERE status <> 'cancelled';
COMMENT ON TABLE biz_production_task IS '客户订单按 PO 派生生产任务，保留套装、子款和颜色尺码配套快照';
COMMENT ON COLUMN biz_production_task.id IS '生产任务内部主键';
COMMENT ON COLUMN biz_production_task.order_id IS '来源客户订单';
COMMENT ON COLUMN biz_production_task.order_revision IS '生成时来源订单版本';
COMMENT ON COLUMN biz_production_task.po_number IS '来源客户 PO 编号';
COMMENT ON COLUMN biz_production_task.task_no IS '生产任务单号';
COMMENT ON COLUMN biz_production_task.status IS '单据状态：草稿、审批中、已审核、已取消';
COMMENT ON COLUMN biz_production_task.revision IS '并发更新版本';
COMMENT ON COLUMN biz_production_task.document IS '生产规格、子款配套、订单数量、计划数量及排产信息快照';
COMMENT ON COLUMN biz_production_task.workflow_instance_id IS '统一审批流程实例编号';
COMMENT ON COLUMN biz_production_task.created_by IS '创建人';
COMMENT ON COLUMN biz_production_task.created_at IS '创建时间';
COMMENT ON COLUMN biz_production_task.updated_at IS '最近修改时间';
DO $$ DECLARE app_role text;
BEGIN
    SELECT pg_get_userbyid(relowner) INTO STRICT app_role FROM pg_class WHERE oid='public.sys_tag'::regclass;
    EXECUTE format('GRANT SELECT, INSERT, UPDATE ON biz_material_demand_plan, biz_production_task TO %I',app_role);
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE biz_material_demand_plan_id_seq, biz_production_task_id_seq TO %I',app_role);
END $$;
COMMIT;
