-- 客户订单派生的物料需求计划与生产任务。业务数据和审批过程分离。
BEGIN;
CREATE TABLE IF NOT EXISTS biz_material_demand_plan (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES biz_customer_order(id),
    order_revision integer NOT NULL,
    plan_no varchar(64) NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','submitted','approved','cancelled')),
    revision integer NOT NULL DEFAULT 1,
    document jsonb NOT NULL,
    workflow_instance_id bigint,
    created_by bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_material_demand_plan_no UNIQUE(plan_no)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_material_demand_plan_active_order ON biz_material_demand_plan(order_id) WHERE status <> 'cancelled';
COMMENT ON TABLE biz_material_demand_plan IS '客户订单派生物料需求计划，保留 BOM、采购单位和库存单位需求快照';
COMMENT ON COLUMN biz_material_demand_plan.order_id IS '来源客户订单主键，关联 biz_customer_order.id；每张有效订单最多保留一张未取消需求计划';
COMMENT ON COLUMN biz_material_demand_plan.order_revision IS '生成本计划时的来源订单修订号，用于识别算料依据是否已变化';
COMMENT ON COLUMN biz_material_demand_plan.plan_no IS '物料需求计划单号，全表唯一，供业务查询及审批引用';
COMMENT ON COLUMN biz_material_demand_plan.status IS '单据状态：draft 草稿、submitted 审批中、approved 已审核、cancelled 已取消';
COMMENT ON COLUMN biz_material_demand_plan.revision IS '计划单并发修订号，创建时为1，每次成功修改递增';
COMMENT ON COLUMN biz_material_demand_plan.document IS '需求计划 JSON 明细，记录订单/PO/款式规格/物料/颜色/物料规格、库存单位与采购单位数量、单位换算及计划人员调整';
COMMENT ON COLUMN biz_material_demand_plan.workflow_instance_id IS '该计划对应的 Warm-Flow 审批实例编号；未提交审批时为空';
COMMENT ON COLUMN biz_material_demand_plan.created_by IS '创建计划单的员工账号，关联 sys_user.user_id';
COMMENT ON COLUMN biz_material_demand_plan.created_at IS '需求计划首次生成时间';
COMMENT ON COLUMN biz_material_demand_plan.updated_at IS '需求计划最近一次保存时间';
COMMENT ON COLUMN biz_material_demand_plan.id IS '物料需求计划内部主键，供审批关联和业务查询使用';
CREATE TABLE IF NOT EXISTS biz_production_task (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES biz_customer_order(id),
    order_revision integer NOT NULL,
    po_number varchar(100) NOT NULL,
    task_no varchar(64) NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','submitted','approved','cancelled')),
    revision integer NOT NULL DEFAULT 1,
    document jsonb NOT NULL,
    workflow_instance_id bigint,
    created_by bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_production_task_no UNIQUE(task_no)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_production_task_active_po ON biz_production_task(order_id,lower(po_number)) WHERE status <> 'cancelled';
COMMENT ON TABLE biz_production_task IS '客户订单按 PO 派生生产任务，保留套装、子款和颜色尺码配套快照';
COMMENT ON COLUMN biz_production_task.id IS '生产任务内部主键，供生产执行记录关联';
COMMENT ON COLUMN biz_production_task.order_id IS '来源客户订单主键，关联 biz_customer_order.id';
COMMENT ON COLUMN biz_production_task.order_revision IS '生成任务时的来源订单修订号，用于追踪生产安排依据';
COMMENT ON COLUMN biz_production_task.po_number IS '来源客户 PO 编号；同一订单每个未取消 PO 对应一张任务';
COMMENT ON COLUMN biz_production_task.task_no IS '生产任务单号，全表唯一，供生产现场检索和单据引用';
COMMENT ON COLUMN biz_production_task.status IS '单据状态：draft 草稿、submitted 审批中、approved 已审核、cancelled 已取消';
COMMENT ON COLUMN biz_production_task.revision IS '生产任务并发修订号，创建时为1，每次成功修改递增';
COMMENT ON COLUMN biz_production_task.document IS '生产任务 JSON 快照，记录订单款式、套装子款配套、颜色尺码数量及排产信息';
COMMENT ON COLUMN biz_production_task.workflow_instance_id IS '该任务对应的 Warm-Flow 审批实例编号；未提交审批时为空';
COMMENT ON COLUMN biz_production_task.created_by IS '创建生产任务的员工账号，关联 sys_user.user_id';
COMMENT ON COLUMN biz_production_task.created_at IS '生产任务首次生成时间';
COMMENT ON COLUMN biz_production_task.updated_at IS '生产任务最近一次保存时间';
DO $$ DECLARE app_role text;
BEGIN
    SELECT pg_get_userbyid(relowner) INTO STRICT app_role FROM pg_class WHERE oid='public.sys_tag'::regclass;
    EXECUTE format('GRANT SELECT, INSERT, UPDATE ON biz_material_demand_plan, biz_production_task TO %I',app_role);
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE biz_material_demand_plan_id_seq, biz_production_task_id_seq TO %I',app_role);
END $$;
COMMIT;
