INSERT INTO sys_menu(menu_id,parent_id,menu_name,order_num,path,component,is_frame,is_cache,menu_type,visible,status,perms,icon,create_time)
SELECT v.id,m.menu_id,v.name,v.seq,'#','','N','Y','F','0','0',v.perm,'#',now()
