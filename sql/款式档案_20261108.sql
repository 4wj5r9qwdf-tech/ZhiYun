    (1762900000000000102::bigint,'新增款式',1,'rd:style:add'),
    (1762900000000000103::bigint,'编辑与启停款式',2,'rd:style:edit'),
    (1762900000000000104::bigint,'删除款式',3,'rd:style:remove')
