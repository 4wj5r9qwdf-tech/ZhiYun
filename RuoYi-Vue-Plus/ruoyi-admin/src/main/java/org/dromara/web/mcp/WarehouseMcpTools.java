package org.dromara.web.mcp;

import cn.dev33.satoken.stp.StpUtil;
import lombok.RequiredArgsConstructor;
import org.dromara.common.core.domain.R;
import org.dromara.web.controller.WarehouseController;
import org.dromara.web.controller.WarehouseLocationController;
import org.dromara.system.controller.system.SysConfigController;
import org.springframework.ai.mcp.annotation.McpTool;
import org.springframework.ai.mcp.annotation.McpToolParam;
import org.springframework.stereotype.Component;

import java.util.Map;

/**
 * 已验收仓储资料的只读 MCP 工具。权限在工具入口显式校验，因为直接调用
 * Controller Java 方法不会触发 Spring MVC 的 Sa-Token 注解拦截。
 */
@Component
@RequiredArgsConstructor
public class WarehouseMcpTools {

    private final WarehouseController warehouseController;
    private final WarehouseLocationController locationController;
    private final SysConfigController configController;

    @McpTool(name = "warehouse_list", description = "按关键词、状态和类型标签查询仓库档案；需要 inventory:warehouse:list 权限")
    public R<?> warehouseList(
        @McpToolParam(description = "可选，仓库编码、名称、区域或建筑名称关键词") String keyword,
        @McpToolParam(description = "可选，0启用、1停用") String status,
        @McpToolParam(description = "可选，仓库类型标签ID") String tagId) {
        StpUtil.checkPermission("inventory:warehouse:list");
        return warehouseController.list(keyword, status, tagId);
    }

    @McpTool(name = "warehouse_get", description = "按仓库ID查询仓库档案详情和类型标签；需要 inventory:warehouse:query 权限")
    public R<?> warehouseGet(@McpToolParam(description = "仓库ID，十进制字符串") String warehouseId) {
        StpUtil.checkPermission("inventory:warehouse:query");
        return warehouseController.detail(Long.valueOf(warehouseId));
    }

    @McpTool(name = "warehouse_form_options", description = "查询仓库表单可选的在用建筑和负责人；需要有效员工登录")
    public R<?> warehouseFormOptions() {
        StpUtil.checkLogin();
        return warehouseController.options();
    }

    @McpTool(name = "warehouse_next_code", description = "查询当前仓库自动编码规则给出的下一个编码建议；需要 inventory:warehouse:add 权限")
    public R<?> warehouseNextCode() {
        StpUtil.checkPermission("inventory:warehouse:add");
        return warehouseController.nextCode();
    }

    @McpTool(name = "warehouse_create", description = "新增仓库档案；这是写操作，调用前必须已向员工展示完整内容并取得确认，需要 inventory:warehouse:add 权限")
    public R<?> warehouseCreate(@McpToolParam(description = "仓库字段对象：warehouseCode、autoGeneratedCode、warehouseName、buildingId、floorName、areaName、managerUserId、inboundLocationLevel、status、remark、tagIds") Map<String, Object> body) {
        StpUtil.checkPermission("inventory:warehouse:add");
        return warehouseController.add(body);
    }

    @McpTool(name = "warehouse_update", description = "修改仓库档案；这是写操作，调用前必须已向员工展示完整变更并取得确认，需要 inventory:warehouse:edit 权限")
    public R<?> warehouseUpdate(@McpToolParam(description = "完整仓库字段对象，必须包含 warehouseId") Map<String, Object> body) {
        StpUtil.checkPermission("inventory:warehouse:edit");
        return warehouseController.edit(body);
    }

    @McpTool(name = "warehouse_set_status", description = "启用或停用仓库；这是写操作，调用前必须取得员工确认，需要 inventory:warehouse:edit 权限")
    public R<?> warehouseSetStatus(
        @McpToolParam(description = "仓库ID，十进制字符串") String warehouseId,
        @McpToolParam(description = "0启用、1停用") String status) {
        StpUtil.checkPermission("inventory:warehouse:edit");
        return warehouseController.changeStatus(Long.valueOf(warehouseId), Map.of("status", status));
    }

    @McpTool(name = "warehouse_delete", description = "逻辑删除仓库；不可逆业务动作，必须展示仓库身份并取得员工本次确认，需要 inventory:warehouse:remove 权限")
    public R<?> warehouseDelete(@McpToolParam(description = "仓库ID，十进制字符串") String warehouseId) {
        StpUtil.checkPermission("inventory:warehouse:remove");
        return warehouseController.remove(Long.valueOf(warehouseId));
    }

    @McpTool(name = "warehouse_set_code_rule", description = "修改仓库自动编码规则；必须展示旧规则和完整新规则并取得员工确认，需要 system:config:edit 权限")
    public R<?> warehouseSetCodeRule(@McpToolParam(description = "规则对象：enabled布尔值、prefix字母数字前缀、digits序号位数1至10") Map<String, Object> rule) {
        StpUtil.checkPermission("system:config:edit");
        return configController.updateWarehouseCodeRule(rule);
    }

    @McpTool(name = "warehouse_layout_options", description = "查询仓库布局可选仓库及入库定位层级；需要有效员工登录")
    public R<?> warehouseLayoutOptions() {
        StpUtil.checkLogin();
        return locationController.options();
    }

    @McpTool(name = "warehouse_layout_tree", description = "按仓库查询库区、货架、货位层级树；需要 inventory:location:list 权限")
    public R<?> warehouseLayoutTree(
        @McpToolParam(description = "可选，仓库ID，十进制字符串；不传查询全部仓库") String warehouseId) {
        StpUtil.checkPermission("inventory:location:list");
        return locationController.tree(warehouseId == null || warehouseId.isBlank() ? null : Long.valueOf(warehouseId));
    }

    @McpTool(name = "warehouse_layout_list", description = "按仓库、父级、层级、关键词和状态查询库区/货架/货位；需要 inventory:location:list 权限")
    public R<?> warehouseLayoutList(
        @McpToolParam(description = "仓库ID，十进制字符串") String warehouseId,
        @McpToolParam(description = "可选，上级位置ID，十进制字符串") String parentId,
        @McpToolParam(description = "可选，1库区、2货架、3货位") Integer level,
        @McpToolParam(description = "可选，位置编码或名称关键词") String keyword,
        @McpToolParam(description = "可选，active启用、disabled停用、maintenance维护") String status) {
        StpUtil.checkPermission("inventory:location:list");
        return locationController.list(Long.valueOf(warehouseId),
            parentId == null || parentId.isBlank() ? null : Long.valueOf(parentId), level, keyword, status);
    }

    @McpTool(name = "warehouse_layout_get", description = "按位置ID查询仓储位置详情及父级信息；需要 inventory:location:query 权限")
    public R<?> warehouseLayoutGet(@McpToolParam(description = "仓储位置ID，十进制字符串") String locationId) {
        StpUtil.checkPermission("inventory:location:query");
        return locationController.detail(Long.valueOf(locationId));
    }

    @McpTool(name = "warehouse_layout_next_code", description = "查询指定仓库层级下一个位置编码建议；需要 inventory:location:add 权限")
    public R<?> warehouseLayoutNextCode(
        @McpToolParam(description = "仓库ID，十进制字符串") String warehouseId,
        @McpToolParam(description = "可选，父级位置ID；库区不传") String parentLocationId,
        @McpToolParam(description = "层级：1库区、2货架、3货位") Integer locationLevel) {
        StpUtil.checkPermission("inventory:location:add");
        return locationController.nextCode(Long.valueOf(warehouseId),
            parentLocationId == null || parentLocationId.isBlank() ? null : Long.valueOf(parentLocationId), locationLevel);
    }

    @McpTool(name = "warehouse_layout_create", description = "新增库区、货架或货位；这是写操作，调用前必须展示仓库、父级、层级及档案字段并取得员工确认，需要 inventory:location:add 权限")
    public R<?> warehouseLayoutCreate(@McpToolParam(description = "位置字段对象：warehouseId、parentLocationId、locationLevel、locationCode、autoGeneratedCode、locationName、agvReachable、capacityLimit、capacityUnit、locationStatus、externalLocationCode、remark") Map<String, Object> body) {
        StpUtil.checkPermission("inventory:location:add");
        return locationController.add(body);
    }

    @McpTool(name = "warehouse_layout_update", description = "修改仓储位置属性；仓库、层级、父级和编码不可改变；调用前必须取得员工确认，需要 inventory:location:edit 权限")
    public R<?> warehouseLayoutUpdate(@McpToolParam(description = "完整位置字段对象，必须包含 locationId") Map<String, Object> body) {
        StpUtil.checkPermission("inventory:location:edit");
        return locationController.edit(body);
    }

    @McpTool(name = "warehouse_layout_set_status", description = "启用、停用或设为维护状态；调用前必须取得员工确认，需要 inventory:location:edit 权限")
    public R<?> warehouseLayoutSetStatus(
        @McpToolParam(description = "位置ID，十进制字符串") String locationId,
        @McpToolParam(description = "active启用、disabled停用、maintenance维护") String locationStatus) {
        StpUtil.checkPermission("inventory:location:edit");
        return locationController.changeStatus(Long.valueOf(locationId), Map.of("locationStatus", locationStatus));
    }

    @McpTool(name = "warehouse_layout_delete", description = "逻辑删除无子级且未被业务引用的位置；必须展示完整层级路径并取得员工本次确认，需要 inventory:location:remove 权限")
    public R<?> warehouseLayoutDelete(@McpToolParam(description = "位置ID，十进制字符串") String locationId) {
        StpUtil.checkPermission("inventory:location:remove");
        return locationController.remove(Long.valueOf(locationId));
    }

    @McpTool(name = "warehouse_layout_set_code_rule", description = "修改库区、货架、货位自动编码规则；必须展示旧规则和完整新规则并取得员工确认，需要 system:config:edit 权限")
    public R<?> warehouseLayoutSetCodeRule(@McpToolParam(description = "规则对象：enabled、zonePrefix/zoneDigits、rackPrefix/rackDigits、binPrefix/binDigits") Map<String, Object> rule) {
        StpUtil.checkPermission("system:config:edit");
        return configController.updateWarehouseLayoutCodeRule(rule);
    }
}
