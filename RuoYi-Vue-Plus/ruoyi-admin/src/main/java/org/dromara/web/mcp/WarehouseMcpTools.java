    /**
     * 顺序执行最多一千条位置新增，逐条保留现有事务、校验和业务审计，并汇总部分成功结果。
     * Create up to 1000 locations sequentially, preserving per-row transactions, validation, and audit.
     */
    @McpTool(name = "warehouse_layout_batch_create", description = "批量新增最多1000条库区、货架或货位；逐条校验并允许部分成功，返回每行结果。执行前必须展示全部行和可能部分成功的影响并取得员工确认，需要 inventory:location:add 权限")
    public R<?> warehouseLayoutBatchCreate(@McpToolParam(description = "待新增位置字段对象数组；每行结构与 warehouse_layout_create 相同，需含 warehouseId、parentLocationId、locationLevel、locationCode、autoGeneratedCode、locationName 等字段") List<Map<String, Object>> rows) {
        StpUtil.checkPermission("inventory:location:add");
        if (rows == null || rows.isEmpty() || rows.size() > 1000) {
            return R.fail("请提供1到1000条待新增仓储位置");
        }

        List<Map<String, Object>> results = new ArrayList<>(rows.size());
        int successCount = 0;
        for (int index = 0; index < rows.size(); index++) {
            Map<String, Object> input = rows.get(index);
            Map<String, Object> result = new LinkedHashMap<>();
            result.put("row", index + 1);
            if (input == null) {
                result.put("success", false);
                result.put("reason", "位置字段不能为空");
                results.add(result);
                continue;
            }

            // Controller 会在更新后的 Map 中回填最终编码，因此先复制 MCP 输入行。
            Map<String, Object> payload = new LinkedHashMap<>(input);
            payload.put("entrySource", "csv_import");
            result.put("locationName", payload.getOrDefault("locationName", ""));
            result.put("locationCode", payload.getOrDefault("locationCode", ""));
            ServletUtils.getRequest().removeAttribute("zhiyun.audit");
            try {
                R<?> response = locationController.add(payload);
                boolean succeeded = response.getCode() == 200;
                result.put("success", succeeded);
                if (succeeded) {
                    successCount++;
                    result.put("locationCode", response.getData());
                } else {
                    result.put("reason", response.getMsg());
                }
            } catch (RuntimeException exception) {
                result.put("success", false);
                result.put("reason", "服务端新增异常，请核查该行是否已保存");
            } finally {
                // MCP 批量调用复用一个 HTTP 请求；清除单行审计快照，防止下行误复用上行日志。
                ServletUtils.getRequest().removeAttribute("zhiyun.audit");
            }
            results.add(result);
        }

        return R.ok(Map.of("successCount", successCount, "failureCount", rows.size() - successCount, "results", results));
    }
