    /** 校验仓库新增/完整修改 Map；ID 与标签成员仅接收十进制字符串，空标签清空关联。 / Validate warehouse create and replacement maps with string IDs only. */
    Map<String, Object> warehouseBody(Map<String, Object> body, boolean updating) {
        if (body == null) throw new org.dromara.common.core.exception.ServiceException("仓库字段对象不能为空");
        Set<String> fields = updating
            ? Set.of("warehouseId", "warehouseCode", "warehouseName", "buildingId", "floorName", "areaName", "managerUserId", "inboundLocationLevel", "status", "remark", "tagIds")
            : Set.of("warehouseCode", "autoGeneratedCode", "warehouseName", "buildingId", "floorName", "areaName", "managerUserId", "inboundLocationLevel", "status", "remark", "tagIds");
        for (String key : body.keySet()) if (!fields.contains(key)) throw new org.dromara.common.core.exception.ServiceException("不支持的仓库字段：" + key);
        Set<String> required = updating
            ? Set.of("warehouseId", "warehouseCode", "warehouseName", "buildingId", "floorName", "areaName", "managerUserId", "inboundLocationLevel", "status", "remark", "tagIds")
            : Set.of("warehouseName");
        if (!body.keySet().containsAll(required)) throw new org.dromara.common.core.exception.ServiceException("仓库字段对象缺少必填字段");

        Map<String, Object> normalized = new LinkedHashMap<>(body);
        if (updating) normalized.put("warehouseId", McpInputValidator.requirePositiveId(body.get("warehouseId"), "仓库ID"));
        for (String key : Set.of("buildingId", "managerUserId")) {
            if (!body.containsKey(key)) continue;
            Object raw = body.get(key);
            if (raw == null || raw instanceof String value && value.isBlank()) normalized.put(key, null);
            else normalized.put(key, McpInputValidator.requirePositiveId(raw, key));
        }
        Object rawName = body.get("warehouseName");
        if (!(rawName instanceof String name) || name.isBlank()) throw new org.dromara.common.core.exception.ServiceException("warehouseName必须是非空字符串");
        if (name.trim().length() > 200) throw new org.dromara.common.core.exception.ServiceException("warehouseName超过允许长度");
        if (body.containsKey("warehouseCode")) {
            Object rawCode = body.get("warehouseCode");
            if (rawCode != null && !(rawCode instanceof String)) throw new org.dromara.common.core.exception.ServiceException("warehouseCode必须是字符串或null");
            if (updating && (!(rawCode instanceof String code) || code.isBlank())) throw new org.dromara.common.core.exception.ServiceException("修改仓库时warehouseCode必须为非空字符串");
            if (rawCode instanceof String code && code.trim().length() > 50) throw new org.dromara.common.core.exception.ServiceException("warehouseCode超过50个字符");
        }
        if (!updating && body.containsKey("autoGeneratedCode") && body.get("autoGeneratedCode") != null && !(body.get("autoGeneratedCode") instanceof String)) {
            throw new org.dromara.common.core.exception.ServiceException("autoGeneratedCode必须是字符串或null");
        }
        for (String key : Set.of("floorName", "areaName", "remark")) {
            if (!body.containsKey(key)) continue;
            Object raw = body.get(key);
            if (raw != null && !(raw instanceof String)) throw new org.dromara.common.core.exception.ServiceException(key + "必须是字符串或null");
        }
        Object rawLevel = body.get("inboundLocationLevel");
        if (rawLevel == null && !updating) normalized.put("inboundLocationLevel", 2);
        else if (!(rawLevel instanceof Integer || rawLevel instanceof Long) || ((Number) rawLevel).intValue() < 0 || ((Number) rawLevel).intValue() > 3 || ((Number) rawLevel).longValue() != ((Number) rawLevel).intValue()) {
            throw new org.dromara.common.core.exception.ServiceException("inboundLocationLevel必须为JSON整数0至3");
        } else normalized.put("inboundLocationLevel", ((Number) rawLevel).intValue());
        Object rawStatus = body.get("status");
        if (rawStatus == null && !updating) normalized.put("status", "0");
        else if (!(rawStatus instanceof String status) || !Set.of("0", "1").contains(status)) {
            throw new org.dromara.common.core.exception.ServiceException("status必须是字符串0（启用）或1（停用）");
        }
        Object rawTags = body.get("tagIds");
        if (rawTags == null && !updating) normalized.put("tagIds", List.of());
        else {
            if (!(rawTags instanceof List<?> tags)) throw new org.dromara.common.core.exception.ServiceException("tagIds必须是十进制字符串数组");
            Set<Long> unique = new java.util.HashSet<>();
            List<String> ids = new ArrayList<>();
            for (Object tag : tags) {
                Long id = McpInputValidator.requirePositiveId(tag, "标签ID");
                if (!unique.add(id)) throw new org.dromara.common.core.exception.ServiceException("tagIds不能包含重复ID");
                ids.add(id.toString());
            }
            normalized.put("tagIds", ids);
        }
        return normalized;
    }

    /** 校验仓库自动编码规则对象，防止错误类型被配置接口强制转换。 / Validate the complete warehouse code-rule object. */
    Map<String, Object> codeRuleBody(Map<String, Object> rule) {
        if (rule == null || !rule.keySet().equals(Set.of("enabled", "prefix", "digits"))) {
            throw new org.dromara.common.core.exception.ServiceException("编码规则必须且只能包含enabled、prefix、digits");
        }
        if (!(rule.get("enabled") instanceof Boolean enabled)) throw new org.dromara.common.core.exception.ServiceException("enabled必须是JSON布尔值");
        if (!(rule.get("prefix") instanceof String prefix) || !prefix.matches("[A-Za-z0-9]{1,12}")) {
            throw new org.dromara.common.core.exception.ServiceException("prefix必须为1至12位英文字母或数字");
        }
        Object rawDigits = rule.get("digits");
        if (!(rawDigits instanceof Integer || rawDigits instanceof Long) || ((Number) rawDigits).longValue() < 1 || ((Number) rawDigits).longValue() > 10) {
            throw new org.dromara.common.core.exception.ServiceException("digits必须是JSON整数1至10");
        }
        return Map.of("enabled", enabled, "prefix", prefix, "digits", ((Number) rawDigits).intValue());
    }
