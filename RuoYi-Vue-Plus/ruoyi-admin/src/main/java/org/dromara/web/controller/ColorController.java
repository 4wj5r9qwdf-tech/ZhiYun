/**
 * 全局颜色基础资料，供物料、款式等业务共用；编码是稳定标识，停用只阻止新引用。
 * Global reusable colors; codes remain stable and disabled colors are retained for history.
 */
@RestController
@RequiredArgsConstructor
@RequestMapping("/system/color")
public class ColorController {
    private static final String CODE_RULE_KEY = "base.color.codeRule";
    private static final long CODE_LOCK_KEY = 2026110701L;
    private final JdbcTemplate jdbc;

    /** 管理目录；基础资料规模小，页面按完整结果集筛选分页。 / Load the complete management directory. */
    @SaCheckPermission("system:color:list")
    @GetMapping("/list")
    public R<List<Map<String, Object>>> list() {
        return R.ok(jdbc.queryForList("SELECT color_id::text AS id,color_code AS code,color_name AS name,color_value,sort_order,status,remark FROM base_color ORDER BY sort_order,color_code,color_id"));
    }

    /** 业务选项保留停用记录并标记不可新选，供历史引用显示。 / Keep disabled options for history. */
    @SaCheckLogin
    @GetMapping("/options")
    public R<List<Map<String, Object>>> options() {
        return R.ok(jdbc.queryForList("SELECT color_id::text AS id,color_code AS code,color_name AS name,color_value,status,(status='0') AS selectable FROM base_color ORDER BY sort_order,color_name,color_code"));
    }

    /** 返回可编辑编码建议；正式保存仍在事务锁内重新分配未修改的建议。 / Return an editable, advisory code. */
    @SaCheckPermission("system:color:add")
    @GetMapping("/next-code")
    public R<Map<String, Object>> nextCode() {
        CodeRule rule = codeRule();
        return R.ok(Map.of("enabled", rule.enabled(), "code", rule.enabled() ? nextAvailableCode(rule) : ""));
    }

    /** 新增颜色；相同中文名称或编码不重复建档。 / Create a color with case-insensitive uniqueness. */
    @SaCheckPermission("system:color:add")
    @Log(title = "颜色管理", businessType = BusinessType.INSERT)
    @Transactional(rollbackFor = Exception.class)
    @PostMapping
    public R<String> add(@RequestBody Map<String, Object> body) {
        ColorInput input;
        try { input = validate(body); } catch (IllegalArgumentException e) { return R.fail(e.getMessage()); }
        jdbc.execute("SELECT pg_advisory_xact_lock(" + CODE_LOCK_KEY + ")");
        CodeRule rule = codeRule();
        String requested = value(body, "code");
        String suggested = value(body, "autoGeneratedCode");
        String code = requested;
        if (rule.enabled() && (code.isBlank() || (!suggested.isBlank() && code.equalsIgnoreCase(suggested)))) {
            code = nextAvailableCode(rule);
        }
        if (code.isBlank()) return R.fail("自动生成已关闭，请手动填写颜色编码");
        if (code.length() > 40 || !code.matches("[A-Za-z0-9][A-Za-z0-9_.-]*")) return R.fail("颜色编码须以字母或数字开头，且只能包含字母、数字、点、下划线和短横线");
        if (exists("color_code", code, null)) return R.fail("颜色编码已存在");
        if (exists("color_name", input.name(), null)) return R.fail("颜色名称已存在");
        Long id = jdbc.queryForObject("INSERT INTO base_color(color_code,color_name,color_value,sort_order,remark,create_by) VALUES(?,?,?,?,?,?) RETURNING color_id", Long.class,
            code, input.name(), input.value(), input.sort(), input.remark(), LoginHelper.getUserId());
        BusinessAudit.record("新增颜色", id, "颜色名称", Map.of(), auditSnapshot(id, false));
        return R.ok("操作成功", String.valueOf(id));
    }

    /** 修改显示信息；编码创建后固定，防止引用编码发生漂移。 / Update display fields while keeping identity stable. */
    @SaCheckPermission("system:color:edit")
    @Log(title = "颜色管理", businessType = BusinessType.UPDATE)
    @Transactional(rollbackFor = Exception.class)
    @PutMapping("/{id}")
    public R<Void> edit(@PathVariable Long id, @RequestBody Map<String, Object> body) {
        ColorInput input;
        try { input = validate(body); } catch (IllegalArgumentException e) { return R.fail(e.getMessage()); }
        Map<String, Object> before = auditSnapshot(id, true);
        if (before.isEmpty()) return R.fail("颜色不存在");
        if (exists("color_name", input.name(), id)) return R.fail("颜色名称已存在");
        jdbc.update("UPDATE base_color SET color_name=?,color_value=?,sort_order=?,remark=?,update_by=?,update_time=now() WHERE color_id=?",
            input.name(), input.value(), input.sort(), input.remark(), LoginHelper.getUserId(), id);
        BusinessAudit.record("修改颜色", id, "颜色名称", before, auditSnapshot(id, false));
        return R.ok();
    }

    /** 启停颜色选项；停用不影响已有资料或历史业务显示。 / Change availability without rewriting references. */
    @SaCheckPermission("system:color:edit")
    @Log(title = "颜色状态", businessType = BusinessType.UPDATE)
    @Transactional(rollbackFor = Exception.class)
    @PutMapping("/{id}/status")
    public R<Void> status(@PathVariable Long id, @RequestBody Map<String, Object> body) {
        String status = value(body, "status");
        if (!Set.of("0", "1").contains(status)) return R.fail("状态无效");
        Map<String, Object> before = auditSnapshot(id, true);
        if (before.isEmpty()) return R.fail("颜色不存在");
        if (Objects.equals(status, before.get("状态"))) return R.ok();
        jdbc.update("UPDATE base_color SET status=?,update_by=?,update_time=now() WHERE color_id=?", status, LoginHelper.getUserId(), id);
        BusinessAudit.record(("0".equals(status) ? "启用" : "停用") + "颜色", id, "颜色名称", before, auditSnapshot(id, false));
        return R.ok();
    }

    /** 仅删除尚未被其他档案引用的颜色；被引用后由外键保护，改为停用。 / Delete only unreferenced colors. */
    @SaCheckPermission("system:color:remove")
    @Log(title = "颜色管理", businessType = BusinessType.DELETE)
    @Transactional(rollbackFor = Exception.class)
    @DeleteMapping("/{id}")
    public R<Void> remove(@PathVariable Long id) {
        Map<String, Object> before = auditSnapshot(id, true);
        if (before.isEmpty()) return R.fail("颜色不存在");
        if (hasForeignReferences(id)) return R.fail("该颜色已被基础资料或业务记录引用，不能删除；如不再使用请停用");
        if (jdbc.update("DELETE FROM base_color WHERE color_id=?", id) == 0) return R.fail("颜色不存在");
        BusinessAudit.record("删除颜色", id, "颜色名称", before, Map.of("已删除", true));
        return R.ok();
    }

    /** 仅更新颜色编码规则参数，规则由系统参数页维护。 / Save the validated editable-code rule. */
    @SaCheckPermission("system:config:edit")
    @Log(title = "颜色编码自动生成规则", businessType = BusinessType.UPDATE)
    @Transactional(rollbackFor = Exception.class)
    @PostMapping("/code-rule")
    public R<Void> updateCodeRule(@RequestBody Map<String, Object> body) {
        Object enabled = body.get("enabled"), prefix = body.get("prefix"), digits = body.get("digits");
        if (!(enabled instanceof Boolean) || !(prefix instanceof String p) || p.isBlank() || p.trim().length() > 30
            || !p.trim().matches("[A-Za-z0-9_.-]+") || !(digits instanceof Number n) || n.intValue() < 1 || n.intValue() > 10 || n.doubleValue() != n.intValue()) {
            return R.fail("颜色编码规则无效，请检查开关、编码前缀和序号位数");
        }
        String json = JsonUtils.toJsonString(Map.of("enabled", enabled, "prefix", p.trim(), "digits", n.intValue()));
        String before = jdbc.queryForObject("SELECT config_value FROM sys_config WHERE config_key=? FOR UPDATE", String.class, CODE_RULE_KEY);
        int updated = jdbc.update("UPDATE sys_config SET config_value=?,update_by=?,update_time=now() WHERE config_key=?", json, LoginHelper.getUserId(), CODE_RULE_KEY);
        if (updated == 0) return R.fail("未找到颜色编码规则参数，请先执行颜色管理数据库脚本");
        BusinessAudit.record("修改颜色自动编码规则", CODE_RULE_KEY, "规则", Map.of("规则", before), Map.of("规则", json));
        return R.ok();
    }

    private record ColorInput(String name, String value, int sort, String remark) {}

    /** 校验所有写入字段并归一化色值，避免数据库接受不同格式。 / Validate and normalize user-controlled color fields. */
    private ColorInput validate(Map<String, Object> body) {
        String name = value(body, "name"), color = value(body, "color_value").toUpperCase(Locale.ROOT), remark = value(body, "remark");
        if (name.isBlank() || name.length() > 80) throw new IllegalArgumentException("颜色名称必填且不能超过80个字符");
        if (!color.isBlank() && !color.matches("#[0-9A-F]{6}")) throw new IllegalArgumentException("色值须为六位十六进制颜色，例如 #1E5EFF");
        if (remark.length() > 500) throw new IllegalArgumentException("备注不能超过500个字符");
        int sort;
        try { sort = Integer.parseInt(Objects.toString(body.getOrDefault("sort_order", 0))); }
        catch (Exception e) { throw new IllegalArgumentException("排序必须为整数"); }
        if (sort < 0 || sort > 999999) throw new IllegalArgumentException("排序须在0到999999之间");
        return new ColorInput(name, color, sort, remark);
    }

    private record CodeRule(boolean enabled, String prefix, int digits) {}
    /** 从系统参数读取规则并拒绝损坏配置，避免静默生成错误编码。 / Load and validate the persisted code rule. */
    private CodeRule codeRule() {
        String raw = jdbc.queryForObject("SELECT config_value FROM sys_config WHERE config_key=?", String.class, CODE_RULE_KEY);
        try {
            Map<String, Object> value = JsonUtils.parseMap(raw);
            Object enabled = value.get("enabled"), prefix = value.get("prefix"), digits = value.get("digits");
            if (!(enabled instanceof Boolean e) || !(prefix instanceof String p) || p.isBlank() || p.length() > 30
                || !p.matches("[A-Za-z0-9_.-]+") || !(digits instanceof Number n) || n.intValue() < 1 || n.intValue() > 10) throw new IllegalStateException();
            return new CodeRule(e, p, n.intValue());
        } catch (Exception e) { throw new IllegalStateException("颜色编码规则无效，请在参数设置中修复"); }
    }

    /** 序号锁与唯一索引双重防护，并跳过人工占用的编码。 / Allocate the first free suffix under a transaction lock. */
    private String nextAvailableCode(CodeRule rule) {
        List<String> codes = jdbc.queryForList("SELECT lower(color_code) FROM base_color WHERE lower(color_code) LIKE lower(?)", String.class, rule.prefix() + "%");
        Set<String> used = new java.util.HashSet<>(codes);
        for (long index = 1; index < Long.MAX_VALUE; index++) {
            String serial = Long.toString(index);
            String candidate = rule.prefix() + "0".repeat(Math.max(0, rule.digits() - serial.length())) + serial;
            if (candidate.length() > 40) throw new IllegalStateException("颜色编码超过40个字符，请缩短前缀或减少序号位数");
            if (!used.contains(candidate.toLowerCase(Locale.ROOT))) return candidate;
        }
        throw new IllegalStateException("没有可用的颜色编码序号");
    }

    /** 只允许受控字段进入动态查询，名称和编码按大小写不敏感查重。 / Restrict dynamic columns and enforce case-insensitive uniqueness. */
    private boolean exists(String column, String value, Long excludingId) {
        if (!Set.of("color_code", "color_name").contains(column)) throw new IllegalArgumentException("未知颜色唯一字段");
        String sql = "SELECT count(*) FROM base_color WHERE lower(" + column + ")=lower(?)" + (excludingId == null ? "" : " AND color_id<>?");
        Long count = excludingId == null ? jdbc.queryForObject(sql, Long.class, value) : jdbc.queryForObject(sql, Long.class, value, excludingId);
        return count != null && count > 0;
    }

    /** 查询所有声明到本表的外键引用，避免依赖前端或只检查当前已知业务表。 / Protect future business references too. */
    private boolean hasForeignReferences(Long id) {
        List<Map<String, Object>> refs = jdbc.queryForList("SELECT c.conrelid::regclass::text AS table_name,a.attname AS column_name FROM pg_constraint c JOIN LATERAL unnest(c.conkey) WITH ORDINALITY k(attnum,ord) ON true JOIN pg_attribute a ON a.attrelid=c.conrelid AND a.attnum=k.attnum WHERE c.contype='f' AND c.confrelid='public.base_color'::regclass");
        for (Map<String, Object> ref : refs) {
            String table = Objects.toString(ref.get("table_name"), "");
            String column = Objects.toString(ref.get("column_name"), "");
            if (!table.matches("[A-Za-z0-9_.\"]+") || !column.matches("[A-Za-z0-9_]+")) continue;
            Long count = jdbc.queryForObject("SELECT count(*) FROM " + table + " WHERE \"" + column + "\"=?", Long.class, id);
            if (count != null && count > 0) return true;
        }
        return false;
    }
    /** 将颜色档案的变更整理为字段级业务审计，并避免记录无关请求数据。 / Build a field-level audit snapshot for color changes without retaining unrelated request data. */

    private Map<String, Object> auditSnapshot(Long id, boolean lock) {
        return BusinessAudit.snapshot(jdbc, "SELECT color_code AS \"颜色编码\",color_name AS \"颜色名称\",color_value AS \"色值\",sort_order AS \"排序\",status AS \"状态\",remark AS \"备注\" FROM base_color WHERE color_id=?" + (lock ? " FOR UPDATE" : ""), id);
    }

    /** 统一读取并去除字符串首尾空白。 / Read a request field as trimmed text. */
    private String value(Map<String, Object> body, String key) { return Objects.toString(body.get(key), "").trim(); }
}
