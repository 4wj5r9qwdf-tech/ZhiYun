    /** 在 Map 进入旧控制器前固定 ID/精确数值的 JSON 类型，避免数字被宽松转换成看似合法的字符串。 / Enforce exact MCP field types before legacy Map handling. */
    Map<String, Object> validateUnitBody(Map<String, Object> body, boolean updating) {
        if (body == null) throw new org.dromara.common.core.exception.ServiceException("单位字段对象不能为空");
        Set<String> allowed = Set.of("code", "name", "symbol", "dimension", "decimalPlaces", "baseUnitId", "factor", "sortOrder", "status", "remark");
        for (String key : body.keySet()) {
            if (!allowed.contains(key)) throw new org.dromara.common.core.exception.ServiceException("不支持的单位字段：" + key);
        }
        for (String key : Set.of("code", "name", "dimension")) {
            if (!(body.get(key) instanceof String value) || value.isBlank()) {
                throw new org.dromara.common.core.exception.ServiceException(key + "必须是非空字符串");
            }
        }
        if (updating && !body.keySet().containsAll(allowed)) {
            throw new org.dromara.common.core.exception.ServiceException("修改单位必须提交全部字段；请先读取当前记录并明确提交参照、系数、精度和状态");
        }
        for (String key : Set.of("symbol", "status", "remark")) {
            if (body.containsKey(key) && body.get(key) != null && !(body.get(key) instanceof String)) {
                throw new org.dromara.common.core.exception.ServiceException(key + "必须是字符串");
            }
        }
        for (String key : Set.of("decimalPlaces", "sortOrder")) {
            Object value = body.get(key);
            if (value != null && (!(value instanceof Number number) || number.doubleValue() != number.intValue())) {
                throw new org.dromara.common.core.exception.ServiceException(key + "必须是整数");
            }
        }
        Map<String, Object> normalized = new HashMap<>(body);
        Object baseUnitId = body.get("baseUnitId");
        if (baseUnitId != null) {
            normalized.put("baseUnitId", McpInputValidator.requirePositiveId(baseUnitId, "参照单位ID").toString());
        }
        Object factor = body.get("factor");
        if (factor != null && !(factor instanceof String)) {
            throw new org.dromara.common.core.exception.ServiceException("factor必须是十进制字符串");
        }
        if (body.containsKey("factor") && factor == null) {
            throw new org.dromara.common.core.exception.ServiceException("factor不能为null；省略时默认为1");
        }
        return normalized;
    }

    /** 收紧颜色自由 Map 的键白名单和 JSON 类型；编辑时拒绝会被忽略的编码字段，避免误报已修改。 / Validate color Map keys and prevent silently ignored code edits. */
    Map<String, Object> validateColorBody(Map<String, Object> body, boolean creating) {
        if (body == null) throw new org.dromara.common.core.exception.ServiceException("颜色字段对象不能为空");
        Set<String> allowed = creating
            ? Set.of("code", "autoGeneratedCode", "name", "color_value", "sort_order", "remark")
            : Set.of("name", "color_value", "sort_order", "remark");
        for (String key : body.keySet()) {
            if (!allowed.contains(key)) throw new org.dromara.common.core.exception.ServiceException("不支持的颜色字段：" + key);
        }
        if (!creating && !body.keySet().containsAll(allowed)) {
            throw new org.dromara.common.core.exception.ServiceException("修改颜色必须提交name、color_value、sort_order、remark完整字段");
        }
        if (!(body.get("name") instanceof String name) || name.isBlank()) {
            throw new org.dromara.common.core.exception.ServiceException("name必须是非空字符串");
        }
        for (String key : Set.of("code", "autoGeneratedCode", "color_value", "remark")) {
            if (body.containsKey(key) && body.get(key) != null && !(body.get(key) instanceof String)) {
                throw new org.dromara.common.core.exception.ServiceException(key + "必须是字符串");
            }
        }
        Object sortOrder = body.get("sort_order");
        if (sortOrder != null && (!(sortOrder instanceof Number number) || number.doubleValue() != number.intValue())) {
            throw new org.dromara.common.core.exception.ServiceException("sort_order必须是整数");
        }
        if (body.containsKey("sort_order") && sortOrder == null) {
            throw new org.dromara.common.core.exception.ServiceException("sort_order不能为null；省略时默认为0");
        }
        return new HashMap<>(body);
    }

    /** 要求颜色编码规则一次提交完整且类型明确，拒绝遗漏或多余字段。 / Require a complete typed color-code rule. */
    Map<String, Object> validateColorCodeRuleBody(Map<String, Object> body) {
        if (body == null || !body.keySet().equals(Set.of("enabled", "prefix", "digits"))) {
            throw new org.dromara.common.core.exception.ServiceException("编码规则必须且只能包含enabled、prefix、digits");
        }
        if (!(body.get("enabled") instanceof Boolean)
            || !(body.get("prefix") instanceof String prefix) || prefix.isBlank()
            || !(body.get("digits") instanceof Number digits) || digits.doubleValue() != digits.intValue()) {
            throw new org.dromara.common.core.exception.ServiceException("编码规则字段类型无效");
        }
        return new HashMap<>(body);
    }

    /** 分类体系 Map 创建使用业务默认值；更新要求完整最终字段。 / Validate category-scheme Maps and require complete replacement updates. */
    Map<String, Object> validateCategorySchemeBody(Map<String, Object> body, boolean updating) {
        Set<String> fields = Set.of("code", "name", "maxDepth", "sortOrder", "status", "remark");
        if (body == null) throw new org.dromara.common.core.exception.ServiceException("分类体系字段对象不能为空");
        for (String key : body.keySet()) {
            if (!fields.contains(key)) throw new org.dromara.common.core.exception.ServiceException("不支持的分类体系字段：" + key);
        }
        if (updating && !body.keySet().containsAll(fields)) {
            throw new org.dromara.common.core.exception.ServiceException("修改分类体系必须提交全部字段");
        }
        for (String key : Set.of("code", "name")) {
            if (!(body.get(key) instanceof String value) || value.isBlank()) {
                throw new org.dromara.common.core.exception.ServiceException(key + "必须是非空字符串");
            }
        }
        validateOptionalText(body, "remark");
        validateOptionalStatus(body, !updating);
        validateOptionalInteger(body, "maxDepth");
        validateOptionalInteger(body, "sortOrder");
        return new HashMap<>(body);
    }

    /** 分类节点 Map 的 ID 必须为字符串；更新完整替换，根级须显式传 parentId:null。 / Validate taxonomy node IDs and replacement fields. */
    Map<String, Object> validateCategoryBody(Map<String, Object> body, boolean updating) {
        Set<String> fields = updating
            ? Set.of("schemeId", "parentId", "code", "name", "sortOrder", "status", "remark")
            : Set.of("schemeId", "parentId", "code", "autoGeneratedCode", "name", "sortOrder", "status", "remark");
        if (body == null) throw new org.dromara.common.core.exception.ServiceException("分类字段对象不能为空");
        for (String key : body.keySet()) {
            if (!fields.contains(key)) throw new org.dromara.common.core.exception.ServiceException("不支持的分类字段：" + key);
        }
        Set<String> required = updating
            ? Set.of("schemeId", "parentId", "code", "name", "sortOrder", "status", "remark")
            : Set.of("schemeId", "name");
        if (!body.keySet().containsAll(required)) throw new org.dromara.common.core.exception.ServiceException("分类字段对象缺少必填字段");

        Map<String, Object> normalized = new HashMap<>(body);
        normalized.put("schemeId", McpInputValidator.requirePositiveId(body.get("schemeId"), "分类体系ID").toString());
        if (body.containsKey("parentId") && body.get("parentId") != null) {
            normalized.put("parentId", McpInputValidator.requirePositiveId(body.get("parentId"), "上级分类ID").toString());
        }
        for (String key : updating ? Set.of("code", "name") : Set.of("name")) {
            if (!(body.get(key) instanceof String value) || value.isBlank()) {
                throw new org.dromara.common.core.exception.ServiceException(key + "必须是非空字符串");
            }
        }
        if (!updating) {
            validateOptionalText(body, "code");
            validateOptionalText(body, "autoGeneratedCode");
        }
        validateOptionalText(body, "remark");
        validateOptionalStatus(body, !updating);
        validateOptionalInteger(body, "sortOrder");
        return normalized;
    }

    /** 可选文本字段只有被明确提供为字符串或null时才转交控制器。 / Validate optional text field types. */
    private void validateOptionalText(Map<String, Object> body, String key) {
        if (body.containsKey(key) && body.get(key) != null && !(body.get(key) instanceof String)) {
            throw new org.dromara.common.core.exception.ServiceException(key + "必须是字符串");
        }
    }

    /** 校验0/1状态字符串；创建允许省略并使用启用默认值。 / Validate lifecycle flags and their create default. */
    private void validateOptionalStatus(Map<String, Object> body, boolean defaultAllowed) {
        if (!body.containsKey("status") && defaultAllowed) return;
        Object raw = body.get("status");
        if (!(raw instanceof String flag) || !Set.of("0", "1").contains(flag)) {
            throw new org.dromara.common.core.exception.ServiceException("status必须是字符串0或1");
        }
    }

    /** 数字字段接受 JSON 整数，不接受字符串、小数和null。 / Accept JSON integers only. */
    private void validateOptionalInteger(Map<String, Object> body, String key) {
        Object raw = body.get(key);
        if (raw != null && (!(raw instanceof Number number) || number.doubleValue() != number.intValue())) {
            throw new org.dromara.common.core.exception.ServiceException(key + "必须是整数");
        }
        if (body.containsKey(key) && raw == null) {
            throw new org.dromara.common.core.exception.ServiceException(key + "不能为null");
        }
    }

