package org.dromara.web.mcp;

import cn.dev33.satoken.stp.StpUtil;
import lombok.RequiredArgsConstructor;
import org.dromara.common.core.domain.R;
import org.dromara.web.controller.CategoryController;
import org.dromara.web.controller.ColorController;
import org.dromara.web.controller.UnitController;
import org.springframework.ai.mcp.annotation.McpTool;
import org.springframework.ai.mcp.annotation.McpToolParam;
import org.springframework.stereotype.Component;

import java.util.Map;

/**
 * 颜色、计量单位和分类体系的 MCP 适配层；每个工具显式检查员工权限后委托现有控制器。
 * MCP adapter for colors, measurement units and taxonomies; each tool checks employee access before delegating.
 */
@Component
@RequiredArgsConstructor
public class FoundationMcpTools {

    private final UnitController units;
    private final CategoryController categories;
    private final ColorController colors;

    /** 查询颜色主档及管理字段。 / List color master records and their management fields. */
    @McpTool(name = "color_list", description = "查询颜色管理目录，需要 system:color:list 权限")
    public R<?> colorList() {
        StpUtil.checkPermission("system:color:list");
        return colors.list();
    }

    /** 查询业务可选颜色；停用颜色只用于历史记录回显。 / List business color options, including disabled values marked for history-only display. */
    @McpTool(name = "color_options", description = "查询颜色选项；停用颜色仅用于历史显示并带 selectable=false，需要员工登录")
    public R<?> colorOptions() {
        StpUtil.checkLogin();
        return colors.options();
    }

    /** 取得颜色编码建议；建议值仍可编辑，正式保存由服务端重新校验。 / Get an editable color-code suggestion; the server validates the final code on save. */
    @McpTool(name = "color_next_code", description = "获取下一条可编辑颜色编码建议，需要 system:color:add 权限")
    public R<?> colorNextCode() {
        StpUtil.checkPermission("system:color:add");
        return colors.nextCode();
    }

    /** 新增颜色档案；调用前展示全部字段并取得员工本次确认。 / Create a color after presenting all fields and receiving the employee's confirmation. */
    @McpTool(name = "color_create", description = "新增全局颜色档案；调用前展示编码、名称、色值、排序和备注并取得员工确认，需要 system:color:add 权限")
    public R<?> colorCreate(
        @McpToolParam(description = "颜色字段对象：code、autoGeneratedCode、name、color_value、sort_order、remark；自动编码建议可编辑，色值可空")
        Map<String, Object> body) {
        StpUtil.checkPermission("system:color:add");
        return colors.add(body);
    }

    /** 更新颜色名称、屏幕色值、排序和备注；编码属于稳定标识，不在编辑中更改。 / Update color display fields while keeping its code stable. */
    @McpTool(name = "color_update", description = "修改颜色名称、屏幕色值、排序或备注；编码固定，调用前展示前后变化并取得员工确认，需要 system:color:edit 权限")
    public R<?> colorUpdate(
        @McpToolParam(description = "颜色ID正十进制字符串") String id,
        @McpToolParam(description = "完整颜色字段对象：name、color_value、sort_order、remark") Map<String, Object> body) {
        StpUtil.checkPermission("system:color:edit");
        return colors.edit(McpInputValidator.requirePositiveId(id, "颜色ID"), body);
    }

    /** 启用或停用颜色；停用不会删除历史业务关联。 / Change color availability without deleting historical business references. */
    @McpTool(name = "color_set_status", description = "启用或停用颜色；停用阻止新的业务引用但保留历史显示，调用前取得员工确认，需要 system:color:edit 权限")
    public R<?> colorSetStatus(
        @McpToolParam(description = "颜色ID正十进制字符串") String id,
        @McpToolParam(description = "目标状态：0启用、1停用") String status) {
        StpUtil.checkPermission("system:color:edit");
        return colors.status(McpInputValidator.requirePositiveId(id, "颜色ID"),
            Map.of("status", McpInputValidator.requireBinaryFlag(status, "颜色状态")));
    }

    /** 删除无任何基础资料或业务记录引用的颜色。 / Delete a color only when no master or business record references it. */
    @McpTool(name = "color_delete", description = "删除未被任何基础资料或业务记录引用的颜色；调用前展示编码和名称并取得本次确认，需要 system:color:remove 权限")
    public R<?> colorDelete(@McpToolParam(description = "颜色ID正十进制字符串") String id) {
        StpUtil.checkPermission("system:color:remove");
        return colors.remove(McpInputValidator.requirePositiveId(id, "颜色ID"));
    }

    /** 调整颜色自动编码建议规则；调用前展示旧规则、新规则和对后续编码的影响。 / Change the color-code suggestion rule after showing its impact. */
    @McpTool(name = "color_set_code_rule", description = "修改颜色自动编码开关、前缀和位数；展示新旧规则并取得员工确认，需要 system:config:edit 权限")
    public R<?> colorSetCodeRule(
        @McpToolParam(description = "规则对象：enabled布尔值、prefix字符串、digits整数1到10") Map<String, Object> body) {
        StpUtil.checkPermission("system:config:edit");
        return colors.updateCodeRule(body);
    }

    /** 查询计量单位管理目录，含换算关系和精度设置。 / List measurement units with their conversion and precision settings. */
    @McpTool(name = "unit_list", description = "查询全局计量单位目录，需要 system:unit:list 权限")
    public R<?> unitList() {
        StpUtil.checkPermission("system:unit:list");
        return units.list();
    }

    /** 查询单位业务选项，返回项会标记是否允许新建引用。 / Read unit options and whether each may be newly referenced. */
    @McpTool(name = "unit_options", description = "查询公共单位选项，selectable标记是否可新增引用，需要员工登录")
    public R<?> unitOptions() {
        StpUtil.checkLogin();
        return units.options();
    }

    /** 按公共固定换算关系换算数量；只允许同参照单位的启用单位之间转换。 / Convert between active units that share the same fixed reference unit. */
    @McpTool(name = "unit_convert", description = "同参照单位固定换算，按目标单位精度四舍五入；仅供公共固定换算，不适用于物料专属换算，需要员工登录")
    public R<?> unitConvert(
        @McpToolParam(description = "源单位正十进制ID字符串") String fromId,
        @McpToolParam(description = "目标单位正十进制ID字符串") String toId,
        @McpToolParam(description = "非负普通十进制数量字符串，不使用科学计数法") String quantity) {
        StpUtil.checkLogin();
        return units.convert(fromId, toId, quantity);
    }

    /** 新增单位及其公共换算关系；保存前须展示所有字段并取得确认。 / Create a unit and shared conversion rule after employee confirmation. */
    @McpTool(name = "unit_create", description = "新增计量单位；写操作前必须展示完整内容并取得员工确认，需要 system:unit:add 权限")
    public R<?> unitCreate(
        @McpToolParam(description = "单位字段code、name、symbol、dimension、decimalPlaces、baseUnitId、factor、sortOrder、status、remark；ID和系数用字符串")
        Map<String, Object> body) {
        StpUtil.checkPermission("system:unit:add");
        return units.add(body);
    }

    /** 修改单位字段及状态；被引用的单位不能随意改变原换算语义。 / Update a unit while preserving protected conversion meaning. */
    @McpTool(name = "unit_update", description = "修改计量单位及状态；必须先展示前后差异并取得员工确认，需要 system:unit:edit 权限")
    public R<?> unitUpdate(
        @McpToolParam(description = "单位正十进制ID字符串") String id,
        @McpToolParam(description = "完整单位字段对象，结构同unit_create") Map<String, Object> body) {
        StpUtil.checkPermission("system:unit:edit");
        return units.edit(McpInputValidator.requirePositiveId(id, "单位ID"), body);
    }

    /** 删除未被其他档案引用的单位。 / Delete a unit only when no other record references it. */
    @McpTool(name = "unit_delete", description = "删除无引用单位；必须展示编码名称并取得员工本次确认，需要 system:unit:remove 权限")
    public R<?> unitDelete(@McpToolParam(description = "单位正十进制ID字符串") String id) {
        StpUtil.checkPermission("system:unit:remove");
        return units.remove(McpInputValidator.requirePositiveId(id, "单位ID"));
    }

    /** 查询可管理的全部分类体系。 / List all manageable taxonomy schemes. */
    @McpTool(name = "category_schemes", description = "查询全部分类体系，需要 system:category:list 权限")
    public R<?> categorySchemes() {
        StpUtil.checkPermission("system:category:list");
        return categories.schemes();
    }

    /** 查询业务表单可用的分类体系；停用体系可用于历史回显。 / Read taxonomy options for business forms, including disabled historical values. */
    @McpTool(name = "category_scheme_options", description = "查询公共分类体系选项，停用项仅供历史显示，需要员工登录")
    public R<?> categorySchemeOptions() {
        StpUtil.checkLogin();
        return categories.schemeOptions();
    }

    /** 查询指定分类体系的完整树节点。 / List all nodes in the requested taxonomy scheme. */
    @McpTool(name = "category_list", description = "查询单体系所有分类节点，需要 system:category:list 权限")
    public R<?> categoryList(@McpToolParam(description = "分类体系正十进制ID字符串") String schemeId) {
        StpUtil.checkPermission("system:category:list");
        return categories.list(McpInputValidator.requirePositiveId(schemeId, "分类体系ID"));
    }

    /** 查询可供业务选择的分类节点；selectable反映节点及其祖先状态。 / Read business-selectable categories with effective ancestor availability. */
    @McpTool(name = "category_options", description = "查询公共分类选项，selectable反映体系和祖先状态，需要员工登录")
    public R<?> categoryOptions(@McpToolParam(description = "分类体系正十进制ID字符串") String schemeId) {
        StpUtil.checkLogin();
        return categories.options(McpInputValidator.requirePositiveId(schemeId, "分类体系ID"));
    }

    /** 新增分类节点；保存前须展示分类体系、父节点路径和全部字段。 / Create a taxonomy node after presenting its scheme, parent path and fields. */
    @McpTool(name = "category_create", description = "新增分类节点；先展示体系和父级路径并取得员工确认，需要 system:category:add 权限")
    public R<?> categoryCreate(
        @McpToolParam(description = "分类字段schemeId、parentId、code、name、sortOrder、status、remark；所有ID使用正十进制字符串")
        Map<String, Object> body) {
        StpUtil.checkPermission("system:category:add");
        return categories.add(body);
    }

    /** 修改分类字段或层级；必须展示移动前后路径及受影响范围。 / Edit or move a category after showing old and new paths. */
    @McpTool(name = "category_update", description = "修改或移动分类；必须展示层级和字段变化并取得员工确认，需要 system:category:edit 权限")
    public R<?> categoryUpdate(
        @McpToolParam(description = "分类正十进制ID字符串") String id,
        @McpToolParam(description = "完整分类字段对象，结构同category_create") Map<String, Object> body) {
        StpUtil.checkPermission("system:category:edit");
        return categories.edit(McpInputValidator.requirePositiveId(id, "分类ID"), body);
    }

    /** 删除无下级且未被业务引用的分类。 / Delete a category only when no children or business records reference it. */
    @McpTool(name = "category_delete", description = "删除无下级及无引用的分类；须取得员工本次确认，需要 system:category:remove 权限")
    public R<?> categoryDelete(@McpToolParam(description = "分类正十进制ID字符串") String id) {
        StpUtil.checkPermission("system:category:remove");
        return categories.remove(McpInputValidator.requirePositiveId(id, "分类ID"));
    }

    /** 新增分类体系并定义其层级深度和编码字段。 / Create a taxonomy scheme with its depth and code settings. */
    @McpTool(name = "category_scheme_create", description = "新增分类体系；须展示完整字段并取得员工确认，需要 system:category:add 权限")
    public R<?> categorySchemeCreate(
        @McpToolParam(description = "体系字段code、name、maxDepth、sortOrder、status、remark") Map<String, Object> body) {
        StpUtil.checkPermission("system:category:add");
        return categories.addScheme(body);
    }

    /** 修改分类体系；需说明启停或层级限制变化对已有分类的影响。 / Update a taxonomy scheme after explaining the effect on its categories. */
    @McpTool(name = "category_scheme_update", description = "修改分类体系及状态；须展示对新业务选择的影响并取得确认，需要 system:category:edit 权限")
    public R<?> categorySchemeUpdate(
        @McpToolParam(description = "分类体系正十进制ID字符串") String id,
        @McpToolParam(description = "完整体系字段，结构同category_scheme_create") Map<String, Object> body) {
        StpUtil.checkPermission("system:category:edit");
        return categories.editScheme(McpInputValidator.requirePositiveId(id, "分类体系ID"), body);
    }

    /** 删除无分类节点且未被业务引用的分类体系。 / Delete a taxonomy scheme only when it has no nodes or business references. */
    @McpTool(name = "category_scheme_delete", description = "删除无分类及无引用的体系；须取得员工本次确认，需要 system:category:remove 权限")
    public R<?> categorySchemeDelete(@McpToolParam(description = "分类体系正十进制ID字符串") String id) {
        StpUtil.checkPermission("system:category:remove");
        return categories.removeScheme(McpInputValidator.requirePositiveId(id, "分类体系ID"));
    }
}
