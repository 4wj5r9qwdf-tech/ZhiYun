    /** 建议单号仅供填写；保存时持锁重新分配，防止并发重复。 / Preview only; allocate again under the save lock. */
    @GetMapping("/next-code")
    @SaCheckPermission({"rd:bom:list","rd:bom:edit"})
    public R<String> nextCode() { return R.data(nextBomCode()); }

    private String nextBomCode() {
        String prefix = "BOM" + java.time.LocalDate.now(java.time.ZoneId.of("Asia/Shanghai")).format(java.time.format.DateTimeFormatter.BASIC_ISO_DATE);
        Set<String> used = new HashSet<>(jdbc.queryForList("SELECT upper(bom_code) FROM rd_style_bom WHERE upper(bom_code) LIKE ?",String.class,prefix+"%"));
        for (long n=1; n<Long.MAX_VALUE; n++) {
            String code = prefix + String.format(Locale.ROOT,"%04d",n);
            if (!used.contains(code)) return code;
        }
        throw new ServiceException("没有可用的 BOM 单号");
    }

    /** 只返回 BOM 可使用的款式，不要求另外授予款式管理权限。 / Return styles eligible for BOM use without granting style-maintenance permissions. */
    @GetMapping("/styles")
    public R<List<Map<String,Object>>> styles() {
        var sql = new StringBuilder("""
            SELECT s.style_id::text AS id,s.internal_code AS "styleCode",s.style_name AS name,
                   s.production_mode AS "productionMode",s.status,s.category_id::text AS "categoryId",c.category_name AS "categoryName",
                   cu.customer_name AS "customerName"
            FROM rd_style s LEFT JOIN base_category c ON c.category_id=s.category_id
            LEFT JOIN customer_master cu ON cu.customer_id=s.customer_id WHERE
            """);
        var args = new ArrayList<Object>();
        categories.appendScope(sql,args,"s.category_id",categories.scope());
        return R.ok(jdbc.queryForList(sql.append(" ORDER BY s.internal_code,s.style_id").toString(),args.toArray()));
    }

    /** 复用款式分类权限和业务默认分类，供 BOM 分类树及选款弹窗使用。 / Reuse style category grants and business defaults for the BOM tree and style picker. */
    @GetMapping("/style-categories")
    public R<Map<String,Object>> styleCategories() {
        var options = categories.options();
        @SuppressWarnings("unchecked")
        var rows = (List<Map<String,Object>>) options.get("rows");
        var configs = jdbc.queryForList("SELECT config_value FROM sys_config WHERE config_key='rd.style.defaultCategoryScheme'",String.class);
        String configured = configs.isEmpty() ? "" : Objects.toString(configs.getFirst(),"").trim();
        boolean invalid = !configured.isEmpty() && rows.stream().noneMatch(row ->
            configured.equals(Objects.toString(row.get("schemeId"),"")) && Boolean.TRUE.equals(row.get("selectable")));
        return R.ok(Map.of("rows",rows,"restricted",Boolean.TRUE.equals(options.get("restricted")),
            "schemeId",invalid ? "" : configured,"invalid",invalid));
    }

    /** 按人员分类权限查询全部 BOM 版本，支持直接筛选。 / List BOM versions within the caller category scope and support direct filtering. */
    @GetMapping("/list")
    public R<List<Map<String,Object>>> all(@RequestParam(required=false) String keyword,
                                            @RequestParam(required=false) String status,
                                            @RequestParam(required=false) String mode,
                                            @RequestParam(required=false) Long styleId) {
        var sql = new StringBuilder("""
            SELECT b.id::text AS id,b.style_id::text AS "styleId",b.bom_code AS "bomCode",b.preparer_id::text AS "preparerId",b.version,b.status,b.remark,
                   b.update_time::text AS revision,b.create_time::text AS "createTime",b.update_time::text AS "updateTime",
                   (SELECT nick_name FROM sys_user WHERE user_id=b.preparer_id) AS "creatorName",
                   (SELECT nick_name FROM sys_user WHERE user_id=b.update_by) AS "updaterName",
                   s.internal_code AS "styleCode",s.style_name AS "styleName",
                   s.production_mode AS "productionMode",c.category_name AS "categoryName",cu.customer_name AS "customerName"
            FROM rd_style_bom b JOIN rd_style s ON s.style_id=b.style_id
            LEFT JOIN base_category c ON c.category_id=s.category_id
            LEFT JOIN customer_master cu ON cu.customer_id=s.customer_id WHERE
            """);
        var args = new ArrayList<Object>();
        categories.appendScope(sql,args,"s.category_id",categories.scope());
        if (keyword!=null && !keyword.isBlank()) {
            sql.append(" AND (s.internal_code ILIKE ? OR s.style_name ILIKE ? OR cu.customer_name ILIKE ? OR b.remark ILIKE ? OR b.bom_code ILIKE ?)");
            for (int i=0;i<5;i++) args.add("%"+keyword.trim()+"%");
        }
        if (status!=null && !status.isBlank()) { sql.append(" AND b.status=?"); args.add(status); }
        if (mode!=null && !mode.isBlank()) { sql.append(" AND s.production_mode=?"); args.add(mode); }
        if (styleId!=null) { sql.append(" AND s.style_id=?"); args.add(styleId); }
        return R.ok(jdbc.queryForList(sql.append(" ORDER BY b.update_time DESC,b.id DESC").toString(),args.toArray()));
    }

    /** 规格选择与现有款式一致，分类受限的子款不返回任何配套数据。 / Use the same specification rules as the style master and withhold pairings for inaccessible child styles. */
    @GetMapping("/context/{styleId}")
    public R<Map<String,Object>> context(@PathVariable Long styleId) {
        var parts = parts(styleId);
        var specs = jdbc.queryForList("""
            SELECT id::text AS id,color_name AS "colorName",size_name AS "sizeName"
            FROM rd_style_set_spec WHERE style_id=? ORDER BY sort_order,id
            """, styleId);
        for (Map<String, Object> spec : specs) {
            spec.put("items", jdbc.queryForList("""
                SELECT i.child_id::text AS "childId",i.color_id::text AS "colorId",i.size_id::text AS "sizeId",
                       s.internal_code || ' · ' || s.style_name AS "childLabel",
                       c.color_name AS "colorName",z.name AS "sizeName",m.quantity
                FROM rd_style_set_spec_item i
                JOIN rd_style_set_spec spec ON spec.id=i.spec_id
                JOIN rd_style_member m ON m.style_id=spec.style_id AND m.child_id=i.child_id
                JOIN rd_style s ON s.style_id=i.child_id
                LEFT JOIN base_color c ON c.color_id=i.color_id
                LEFT JOIN sys_size z ON z.id=i.size_id
                WHERE i.spec_id=? ORDER BY m.sort_order,i.child_id
                """, Long.valueOf(spec.get("id").toString())));
        }
        return R.ok(Map.of("parts",parts,"specs",specs,"usageTypes",USAGE_TYPES,"nextVersion",nextVersion(styleId)));
    }

    /** 建议版本号按款式递增。 / Suggest the next version for the selected style. */
    private long nextVersion(Long styleId) {
        return jdbc.queryForObject("SELECT COALESCE(max(version),0)::bigint+1 FROM rd_style_bom WHERE style_id=?",Long.class,styleId);
    }

