    private static final List<String> USAGE_TYPES = List.of("面布","里布","衬布","网眼","辅料","标识","包装","其他");

    public record Rule(Long childId, String slot, UUID slotId, String usageType, Long colorId, Long sizeId, Long materialId,
                       Long materialVariantId, Long materialColorId, BigDecimal usage, Boolean omitted, String remark, Long usageUnitId, BigDecimal conversionFactor) {}
