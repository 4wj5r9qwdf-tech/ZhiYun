    /** 校验款式色码、分类权限和单位规则后保存草稿；已发布版本不可覆盖。 / Validate style pairs, category access and units before saving; released versions stay immutable. */

    @PostMapping
    @SaCheckPermission({"rd:bom:list","rd:bom:edit"})
    @Transactional
    @Log(title="款式 BOM",businessType=BusinessType.UPDATE)
    public R<String> save(@RequestBody Input input) {
        if (input.styleId()==null || input.rules()==null || input.rules().size()>1000) {
            throw new ServiceException("请选择款式，用料规则最多 1000 行");
        }
        // 与款式写入使用同一事务锁，防止校验后组成或规格改变。
        jdbc.query("SELECT pg_advisory_xact_lock(1976509041)",rs -> {});
        var parts = parts(input.styleId());
        var before = input.id()==null ? Map.<String,Object>of() : version(input.id());
        if (!before.isEmpty() && (!input.styleId().toString().equals(before.get("styleId"))
            || !"draft".equals(before.get("status")) || !Objects.equals(input.revision(),before.get("revision")))) {
            throw new ServiceException("草稿已变化或已发布，请刷新后重试");
        }
        if (!before.isEmpty()) checkStoredScope(readRules(before));
        Long preparerId = input.preparerId()==null ? LoginHelper.getUserId() : input.preparerId();
        if (jdbc.queryForObject("SELECT count(*) FROM sys_user WHERE user_id=? AND del_flag='0' AND status='0'",Long.class,preparerId)==0) throw new ServiceException("请选择在职制单人");
        String bomCode = field(input.bomCode(),60,"BOM 单号");
        if (input.id()==null && (bomCode.isBlank() || bomCode.equalsIgnoreCase(Objects.toString(input.autoGeneratedCode(),"")))) bomCode = nextBomCode();
        if (bomCode.isBlank()) throw new ServiceException("请填写 BOM 单号");
        if (Boolean.TRUE.equals(jdbc.queryForObject("SELECT EXISTS(SELECT 1 FROM rd_style_bom WHERE lower(bom_code)=lower(?) AND (?::bigint IS NULL OR id<>?))",Boolean.class,bomCode,input.id(),input.id()))) throw new ServiceException("BOM 单号已存在，请修改后重试");
        // 在现有事务锁内重新分配未修改的建议值。 / Reallocate unchanged suggestions under the existing transaction lock.
        long versionNumber;
        if (input.id()==null && (input.version()==null || Objects.equals(input.version(),input.suggestedVersion()))) {
            versionNumber = nextVersion(input.styleId());
        } else {
            versionNumber = input.version()==null ? ((Number) before.get("version")).longValue() : input.version();
        }
        if (versionNumber<1 || versionNumber>Integer.MAX_VALUE) throw new ServiceException("版本号必须是 1 至 2147483647 的整数");
        if (Boolean.TRUE.equals(jdbc.queryForObject("""
            SELECT EXISTS(SELECT 1 FROM rd_style_bom WHERE style_id=? AND version=? AND (?::bigint IS NULL OR id<>?))
            """,Boolean.class,input.styleId(),(int) versionNumber,input.id(),input.id()))) {
            throw new ServiceException("该款式已使用此版本号，请修改后重试");
        }
        var partIds = new HashSet<Long>();
        parts.forEach(part -> partIds.add(Long.valueOf(part.get("id").toString())));
        boolean set = !"single".equals(style(input.styleId()).get("productionMode"));
        var saved = new ArrayList<SavedRule>();
        var keys = new HashSet<List<Object>>();
        var positions = new HashMap<UUID,List<Object>>();
        for (Rule source : input.rules()) {
            if (source==null) throw new ServiceException("用料规则不能为空");
            String slot = field(source.slot(),80,"用料位置");
            if (slot.isEmpty() && source.slotId()==null) throw new ServiceException("用料行缺少标识，请重新添加");
            Long child = source.childId();
            if (child==null ? !set || source.colorId()!=null || source.sizeId()!=null : !partIds.contains(child)) {
                throw new ServiceException("用料归属或适用规格无效，整套共用物料按套填写");
            }
            if (child!=null && !validPair(child,source.colorId(),source.sizeId())) {
                throw new ServiceException("用料位置「"+slot+"」的适用色码不在子款有效规格内");
            }
            UUID slotId = positionId(source);
            String usageType = source.usageType();
            // 可先录入物料，裁剪等环节需要用途时再明确指定，不从物料分类猜测。
            if (usageType!=null && !usageType.isBlank() && !USAGE_TYPES.contains(usageType)) {
                throw new ServiceException("用料类型无效");
            }
            if (usageType!=null && usageType.isBlank()) usageType = null;
            var position = Arrays.<Object>asList(child,slot);
            var existing = positions.putIfAbsent(slotId,position);
            if (existing!=null && !existing.equals(position)) {
                throw new ServiceException("同一用料行及其色码例外的归属须一致");
            }
            if (!keys.add(Arrays.asList(slotId,source.colorId(),source.sizeId()))) {
                throw new ServiceException("同一用料位置和适用色码只能填写一条规则");
            }
            if (Boolean.TRUE.equals(source.omitted())) {
                if (source.colorId()==null && source.sizeId()==null) throw new ServiceException("不使用只用于颜色或尺码例外");
                saved.add(new SavedRule(new Rule(child,slot,slotId,usageType,source.colorId(),source.sizeId(),null,null,null,null,true,
                    field(source.remark(),500,"备注"),null,null),"","","","","","",null,null));
                continue;
            }
            if (source.usage()==null || source.usage().signum()<=0 || source.usage().scale()>8
                || source.usage().compareTo(new BigDecimal("1000000000"))>=0) {
                throw new ServiceException("用量须大于零、小于十亿，最多八位小数");
            }
            var material = material(source.materialId(),true);
            String variant = materialVariant(source.materialId(), source.materialVariantId(), Boolean.TRUE.equals(material.get("multiSpec")));
            String materialColor = materialColor(source.materialId(),source.materialColorId());
            Long usageUnit = source.usageUnitId() == null ? Long.valueOf(material.get("unitId").toString()) : source.usageUnitId();
            var unitConfig = usageUnit(source.materialId(),usageUnit,material,source.conversionFactor());
            var rule = new Rule(child,slot,slotId,usageType,source.colorId(),source.sizeId(),source.materialId(),
                source.materialVariantId(),source.materialColorId(),source.usage(),false,field(source.remark(),500,"备注"),
                usageUnit,(BigDecimal)unitConfig.get("factor"));
            saved.add(new SavedRule(rule,material.get("name").toString(),material.get("unitId").toString(),
                material.get("unit").toString(),materialColor,Objects.toString(material.get("materialCategory"),""),
                variant.isEmpty() ? Objects.toString(material.get("materialSpec"),"") : variant,
                unitConfig.get("name").toString(),(BigDecimal)unitConfig.get("factor")));
        }
        if (Boolean.TRUE.equals(input.release()) && saved.isEmpty()) throw new ServiceException("发布前至少配置一条有效用料");
        if (Boolean.TRUE.equals(input.release())) verifyCoverage(input.styleId(),parts,saved,set);
        String status = Boolean.TRUE.equals(input.release()) ? "released" : "draft";
        String remark = field(input.remark(),500,"版本说明");
        String json = JsonUtils.toJsonString(saved);
        Long id = input.id();
        if (id==null) {
            id = jdbc.queryForObject("""
                INSERT INTO rd_style_bom(style_id,version,status,remark,rules,create_by,create_time,update_by,release_by,release_time,bom_code,preparer_id)
                SELECT ?,?,?,?,?::jsonb,?,now(),?,CASE WHEN ? THEN ? ELSE NULL END,
                       CASE WHEN ? THEN now() ELSE NULL END,?,?
                RETURNING id
                """,Long.class,input.styleId(),(int) versionNumber,status,remark,json,LoginHelper.getUserId(),LoginHelper.getUserId(),
                Boolean.TRUE.equals(input.release()),LoginHelper.getUserId(),Boolean.TRUE.equals(input.release()),bomCode,preparerId);
        } else {
            jdbc.update("""
                UPDATE rd_style_bom SET version=?,status=?,remark=?,rules=?::jsonb,update_time=now(),update_by=?,bom_code=?,preparer_id=?,
                release_by=CASE WHEN ? THEN ? ELSE NULL END,release_time=CASE WHEN ? THEN now() ELSE NULL END WHERE id=?
                """,
                (int) versionNumber,status,remark,json,LoginHelper.getUserId(),bomCode,preparerId,Boolean.TRUE.equals(input.release()),LoginHelper.getUserId(),
                Boolean.TRUE.equals(input.release()),id);
        }
        var after = version(id);
        before = new LinkedHashMap<>(before);
        before.remove("revision");
        after.remove("revision");
        BusinessAudit.record(Boolean.TRUE.equals(input.release()) ? "发布款式 BOM" : input.id()==null ? "新增 BOM 草稿" : "修改 BOM 草稿",
            id,"version",before,after);
        return R.ok(null,id.toString());
    }

    /** 核对保存版本的适用范围，逐项定位缺料或规则冲突。 / Check version coverage and identify each missing-material or conflicting-rule case. */
    @GetMapping("/{id}/coverage")
    @Transactional(readOnly=true)
    public R<Map<String,Object>> coverage(@PathVariable Long id) {
        var row = version(id);
        Long styleId = Long.valueOf(row.get("styleId").toString());
        var parts = parts(styleId);
        var rules = readRules(row);
        checkStoredScope(rules);
        var issues = new ArrayList<String>();
        int checked = 0;
        if ("single".equals(style(styleId).get("productionMode"))) {
            for (var pair : validPairs(styleId)) {
                checked++;
                inspect(rules,pair,pairLabel(parts.getFirst(),pair),issues);
            }
        } else {
            var specs = jdbc.queryForList("SELECT id,color_name,size_name FROM rd_style_set_spec WHERE style_id=? ORDER BY sort_order,id",styleId);
            if (specs.isEmpty()) issues.add("款式档案尚未维护套装规格");
            var partMap = new HashMap<String,Map<String,Object>>();
            parts.forEach(part -> partMap.put(part.get("id").toString(),part));
            for (var spec : specs) {
                String label = spec.get("color_name")+" / "+spec.get("size_name");
                try {
                    for (var pair : setSelection(styleId,((Number)spec.get("id")).longValue(),parts)) {
                        checked++;
                        inspect(rules,pair,label+" · "+pairLabel(partMap.get(pair.childId().toString()),pair),issues);
                    }
                } catch (ServiceException e) {
                    issues.add(label+"："+e.getMessage());
                }
            }
        }
        if (checked==0 && issues.isEmpty()) issues.add("款式没有有效的颜色尺码组合");
        return R.ok(Map.of("checked",checked,"issueCount",issues.size(),"issues",issues.stream().limit(100).toList()));
    }
    /** 按实际款式配套展开 BOM 规则，供覆盖校验及订单算料复用。 / Expand BOM rules against real style pairings for coverage checks and order calculations. */

    private void inspect(List<SavedRule> rules,Selection pair,String label,List<String> issues) {
        try {
            requireDemand(rules,pair);
        } catch (ServiceException e) {
            issues.add(label+"："+e.getMessage());
        }
    }
    /** 生成子款颜色尺码组合的业务可读名称。 / Build a readable label for a child-style color-size pairing. */

    private String pairLabel(Map<String,Object> part,Selection pair) {
        return part.get("label")+" · "+optionLabel(part,"colors",pair.colorId())
            +" / "+optionLabel(part,"sizes",pair.sizeId());
    }
    /** 生成包含规格上下文的物料选择项名称。 / Build a material option label with its specification context. */

    private String optionLabel(Map<String,Object> part,String field,Long id) {
        if (id==null) return "未设";
        if (part.get(field) instanceof List<?> options) {
            for (Object option : options) {
                if (option instanceof Map<?,?> values && id.toString().equals(values.get("value"))) {
                    return Objects.toString(values.get("label"));
                }
            }
        }
        return id.toString();
    }

    /** 按实际子款规格展开，保留明细并按库存单位汇总。 / Expand actual child specifications, preserve detail rows and aggregate using inventory units. */
    @GetMapping("/{id}/preview")
    @Transactional(readOnly=true)
    public R<Map<String,Object>> preview(@PathVariable Long id,@RequestParam(defaultValue="1") int count,
                                        @RequestParam(required=false) Long setSpecId,
                                        @RequestParam(required=false) Long colorId,
                                        @RequestParam(required=false) Long sizeId) {
        if (count<1 || count>10000000) throw new ServiceException("试算数量须在 1 至 1000 万之间");
        var row = version(id);
        Long styleId = Long.valueOf(row.get("styleId").toString());
        var parts = parts(styleId);
        var rules = readRules(row);
        checkStoredScope(rules);
        boolean set = !"single".equals(style(styleId).get("productionMode"));
        var selections = set ? setSelection(styleId,setSpecId,parts) : List.of(new Selection(styleId,colorId,sizeId,1));
        if (!set && !concretePair(styleId,colorId,sizeId)) throw new ServiceException("请选择款式有效颜色和尺码");
        var details = new ArrayList<Map<String,Object>>();
        var totals = new LinkedHashMap<List<String>,Map<String,Object>>();
        var gaps = new ArrayList<String>();
        for (var selection : selections) {
            var matched = resolve(rules,selection);
            if (matched.isEmpty()) gaps.add(style(selection.childId()).get("label")+" 缺少适用用料");
            // 试算按“订购套数 × 每套子款件数”展开；以下 BigDecimal 乘法不提前舍入，结果之后写入需求计划 numeric(24,8)。
            // Expand sets as order count × child pieces per set; keep exact products here before demand-plan numeric(24,8) persistence.
            var factor = BigDecimal.valueOf(count).multiply(BigDecimal.valueOf(selection.quantity()));
            appendDemand(matched,factor,style(selection.childId()).get("label").toString(),selection,details,totals);
        }
        if (set) appendDemand(resolve(rules,new Selection(null,null,null,1)),BigDecimal.valueOf(count),"整套共用",null,details,totals);
        return R.ok(Map.of("details",details,"totals",totals.values(),"gaps",gaps));
    }

    /** 提供订单所选规格的快照，套装沿用已配置的配套与每套件数。 / Provide order-selection snapshots; sets use configured child pairings and per-set quantities. */
    public List<Selection> orderSelection(Long id, Long setSpecId, Long colorId, Long sizeId) {
        var parts = parts(id);
        if (!"single".equals(style(id).get("productionMode"))) return setSelection(id,setSpecId,parts);
        if (setSpecId!=null || !concretePair(id,colorId,sizeId)) throw new ServiceException("请选择款式有效颜色和尺码");
        return List.of(new Selection(id,colorId,sizeId,1));
    }

    private void appendDemand(List<SavedRule> rules,BigDecimal factor,String part,Selection selection,List<Map<String,Object>> details,
                              Map<List<String>,Map<String,Object>> totals) {
        for (var saved : rules) {
            var rule = saved.rule();
            // BOM库存需求 = 单位用量 × 版本快照换算系数 × 订单展开数量；十进制乘法保留原精度，不在试算阶段舍入。
            // Inventory demand is usage × snapshotted unit factor × expanded order quantity, with no rounding at preview time.
            var qty = rule.usage().multiply(saved.inventoryFactor()==null ? BigDecimal.ONE : saved.inventoryFactor()).multiply(factor);
            var common = Map.of("material",saved.material(),"materialColor",saved.materialColor(),"unit",saved.unit(),
                "materialId",rule.materialId().toString(),"materialVariantId",Objects.toString(rule.materialVariantId(),""),
                "materialSpec",Objects.toString(saved.materialSpec(),""));
            var detail = new LinkedHashMap<String,Object>(common);
            detail.put("part",part);
            detail.put("materialColorId",Objects.toString(rule.materialColorId(),""));
            detail.put("unitId",saved.unitId());
            detail.put("slot",rule.slot());
            detail.put("slotId",positionId(rule).toString());
            detail.put("usageType",rule.usageType());
            detail.put("materialCategory",saved.materialCategory());
            // 将套装子款实际配套色码写入订单算料快照，不能只依赖可能重复的子款名称。
            // Persist the exact set-child color-size pairing; child-style labels alone may be ambiguous.
            detail.put("sourceChildStyleId",selection==null?null:selection.childId());
            detail.put("sourceColorId",selection==null?null:selection.colorId());
            detail.put("sourceSizeId",selection==null?null:selection.sizeId());
            detail.put("sourceChildCount",selection==null?null:selection.quantity());
            detail.put("quantity",qty.stripTrailingZeros().toPlainString());
            details.add(detail);
            var key = List.of(rule.materialId().toString(),Objects.toString(rule.materialVariantId(),""),Objects.toString(rule.materialColorId(),""),saved.unitId());
            var total = totals.computeIfAbsent(key, ignored -> new LinkedHashMap<>(common));
            var previous = new BigDecimal(Objects.toString(total.get("quantity"),"0"));
            total.put("quantity",previous.add(qty).stripTrailingZeros().toPlainString());
        }
    }

    /** 具体色码优先，颜色和尺码单独命中时须明确配置交叉规则。 / Prefer exact color-size rules; separate color and size matches require an explicit cross-rule. */
    private List<SavedRule> resolve(List<SavedRule> rules,Selection selection) {
        var best = new LinkedHashMap<UUID,SavedRule>();
        var ambiguous = new LinkedHashMap<UUID,String>();
        for (var candidate : rules) {
            var rule = candidate.rule();
            if (!Objects.equals(rule.childId(),selection.childId())
                || rule.colorId()!=null && !rule.colorId().equals(selection.colorId())
                || rule.sizeId()!=null && !rule.sizeId().equals(selection.sizeId())) continue;
            UUID slotId = positionId(rule);
            var previous = best.get(slotId);
            if (previous==null || specificity(rule)>specificity(previous.rule())) {
                best.put(slotId,candidate);
                ambiguous.remove(slotId);
            } else if (specificity(rule)==specificity(previous.rule())) {
                ambiguous.put(slotId,rule.slot().isBlank() ? candidate.material() : rule.slot());
            }
        }
        if (!ambiguous.isEmpty()) throw new ServiceException("颜色与尺码规则同时命中，请补充具体色码规则："+String.join("、",ambiguous.values()));
        return best.values().stream().filter(item -> !Boolean.TRUE.equals(item.rule().omitted())).toList();
    }
    /** 计算规则对颜色尺码的明确程度，以优先采用更具体的规则。 / Score color-size specificity so the most targeted rule is applied first. */

    private int specificity(Rule rule) {
        return (rule.colorId()==null ? 0 : 1)+(rule.sizeId()==null ? 0 : 1);
    }

    /** 发布前核对单款全部有效规格，套装核对已配置的实际配套。 / Before release, verify every valid single-style pair or configured set pairing. */
    private void verifyCoverage(Long styleId,List<Map<String,Object>> parts,List<SavedRule> rules,boolean set) {
        if (!set) {
            var pairs = validPairs(styleId);
            if (pairs.isEmpty()) throw new ServiceException("款式没有有效的颜色尺码组合");
            for (var pair : pairs) requireDemand(rules,pair);
            return;
        }
        var specs = jdbc.queryForList("SELECT id FROM rd_style_set_spec WHERE style_id=?",Long.class,styleId);
        if (specs.isEmpty()) throw new ServiceException("发布套装 BOM 前请在款式档案维护套装规格");
        for (Long spec : specs) for (var pair : setSelection(styleId,spec,parts)) requireDemand(rules,pair);
    }
    /** 要求指定的款式颜色尺码组合解析出有效用料，发布时缺料即阻断。 / Require a valid material demand for a style pair and block release when it is missing. */

    private void requireDemand(List<SavedRule> rules,Selection pair) {
        if (resolve(rules,pair).isEmpty()) {
            throw new ServiceException("此颜色尺码缺少有效用料");
        }
    }
    /** 读取套装规格中各子款实际设置的颜色尺码配套。 / Load the child color-size pairings saved in a set specification. */

    private List<Selection> setSelection(Long styleId,Long specId,List<Map<String,Object>> parts) {
        if (specId==null) throw new ServiceException("请选择套装规格");
        var result = jdbc.query("""
            SELECT i.child_id,i.color_id,i.size_id,m.quantity FROM rd_style_set_spec s
            JOIN rd_style_set_spec_item i ON i.spec_id=s.id
            JOIN rd_style_member m ON m.style_id=s.style_id AND m.child_id=i.child_id
            WHERE s.style_id=? AND s.id=? ORDER BY m.sort_order,m.child_id
            """,(rs,n)->new Selection(rs.getLong(1),rs.getLong(2),rs.getLong(3),rs.getInt(4)),styleId,specId);
        if (result.isEmpty() || result.size()!=parts.size()
            || result.stream().anyMatch(pair -> !validPair(pair.childId(),pair.colorId(),pair.sizeId()))) {
            throw new ServiceException("套装规格与当前子款组成或色码不一致");
        }
        return result;
    }
    /** 读取款式组成并校验子款结构，避免 BOM 引用无效子款。 / Load style members and validate set structure before BOM references are accepted. */

    private List<Map<String,Object>> parts(Long id) {
        var parent = style(id);
        var parts = "single".equals(parent.get("productionMode")) ? List.of(parent) : jdbc.queryForList("""
            SELECT s.style_id::text AS id,s.internal_code || ' · ' || s.style_name AS label,
                   s.category_id AS category,m.quantity
            FROM rd_style_member m JOIN rd_style s ON s.style_id=m.child_id
            WHERE m.style_id=? ORDER BY m.sort_order,s.style_id
            """,id);
        for (var part : parts) {
            if (!categories.categoryAllowed(((Number)part.get("category")).longValue())) {
                throw new ServiceException("部分套装子款超出分类权限，无法访问完整 BOM");
            }
            Long child = Long.valueOf(part.get("id").toString());
            part.put("colors",jdbc.queryForList("""
                SELECT c.color_id::text AS value,c.color_name AS label FROM rd_style_color s
                JOIN base_color c ON c.color_id=s.color_id WHERE s.style_id=? ORDER BY c.color_name,c.color_id
                """,child));
            part.put("sizes",jdbc.queryForList("""
                SELECT z.id::text AS value,z.name AS label FROM rd_style_size s
                JOIN sys_size z ON z.id=s.size_id WHERE s.style_id=? ORDER BY z.name,z.id
                """,child));
            part.put("excluded",jdbc.queryForList("""
                SELECT color_id::text AS "colorId",size_id::text AS "sizeId"
                FROM rd_style_spec_exclusion WHERE style_id=?
                """,child));
            part.remove("category");
        }
        return parts;
    }
    /** 读取款式主档及分类范围，供 BOM 权限和状态校验。 / Load the style and category scope for BOM access and state checks. */

    private Map<String,Object> style(Long id) {
        var result = jdbc.queryForList("""
            SELECT style_id::text AS id,internal_code || ' · ' || style_name AS label,category_id AS category,
                   production_mode AS "productionMode",1 AS quantity FROM rd_style WHERE style_id=?
            """,id);
        if (result.isEmpty() || !categories.categoryAllowed(((Number)result.getFirst().get("category")).longValue())) {
            throw new ServiceException("款式不可用或超出分类权限");
        }
        return result.getFirst();
    }
    /** 生成单款有效颜色尺码组合，并排除明确禁用组合。 / Build valid color-size pairs after applying explicit exclusions. */

    private List<Selection> validPairs(Long id) {
        return jdbc.query("""
            SELECT c.color_id,z.size_id FROM
             (SELECT color_id FROM rd_style_color WHERE style_id=? UNION ALL
              SELECT NULL WHERE NOT EXISTS (SELECT 1 FROM rd_style_color WHERE style_id=?)) c
            CROSS JOIN
             (SELECT size_id FROM rd_style_size WHERE style_id=? UNION ALL
              SELECT NULL WHERE NOT EXISTS (SELECT 1 FROM rd_style_size WHERE style_id=?)) z
            WHERE NOT EXISTS (SELECT 1 FROM rd_style_spec_exclusion e
                WHERE e.style_id=? AND e.color_id=c.color_id AND e.size_id=z.size_id)
            """,(rs,n)->new Selection(id,rs.getObject(1,Long.class),rs.getObject(2,Long.class),1),id,id,id,id,id);
    }
    /** 确认指定子款颜色尺码仍是款式允许的有效组合。 / Verify that a child, color and size remain an allowed pairing. */

    private boolean validPair(Long id,Long color,Long size) {
        if (color==null && size==null) return true;
        return validPairs(id).stream().anyMatch(pair -> (color==null || color.equals(pair.colorId()))
            && (size==null || size.equals(pair.sizeId())));
    }
    /** 判断规则是否明确指定了颜色和尺码。 / Determine whether a rule targets a concrete color-size pair. */

    private boolean concretePair(Long id,Long color,Long size) {
        return validPairs(id).stream().anyMatch(pair -> Objects.equals(color,pair.colorId()) && Objects.equals(size,pair.sizeId()));
    }
    /** 读取物料允许用于 BOM 的颜色，并保留历史选项回显。 / Load BOM-eligible material colors while preserving historical display. */

    @GetMapping("/material/{id}/colors")
    public R<List<Map<String,Object>>> materialColors(@PathVariable Long id) {
        material(id,true);
        return R.ok(jdbc.queryForList("""
            SELECT c.color_id::text AS value,c.color_name AS label FROM inv_material_color m
            JOIN base_color c ON c.color_id=m.color_id WHERE m.material_id=? AND c.status='0' ORDER BY c.color_name
            """,id));
    }
    /** 读取可供 BOM 引用的物料、规格和单位信息。 / Load material, variant and unit data available to BOM rules. */

    private Map<String,Object> material(Long id,boolean active) {
        if (id==null) throw new ServiceException("请选择物料");
        var result = jdbc.queryForList("""
            SELECT m.category_id AS category,m.del_flag,m.status,m.multi_spec AS "multiSpec",
                   m.material_code || ' · ' || m.material_name AS name,u.unit_id::text AS "unitId",u.unit_name AS unit,
                   u.status AS "unitStatus",u.del_flag AS "unitDeleted",
                   cs.scheme_name || ' / ' || c.category_name AS "materialCategory",m.specification AS "materialSpec"
            FROM inv_material m JOIN base_unit u ON u.unit_id=m.inventory_unit_id
            LEFT JOIN base_category c ON c.category_id=m.category_id
            LEFT JOIN base_category_scheme cs ON cs.scheme_id=c.scheme_id WHERE m.material_id=?
            """,id);
        if (result.isEmpty()) throw new ServiceException("BOM 引用的物料不存在");
        var row = result.getFirst();
        long category = ((Number)row.get("category")).longValue();
        if (!categories.categoryAllowed(category)) throw new ServiceException("BOM 含超出分类权限的物料");
        if (active && (!"0".equals(row.get("status")) || !"0".equals(row.get("del_flag"))
            || !"0".equals(row.get("unitStatus")) || !"0".equals(row.get("unitDeleted")) || !categories.categoryIsActive(category))) {
            throw new ServiceException("物料或库存单位已停用");
        }
        return row;
    }

    /** 验证规格归属并保存名称快照，防止选错物料。 / Validate ownership and snapshot the selected variant label. */
    private String materialVariant(Long materialId, Long variantId, boolean multiSpec) {
        if (variantId == null) {
            if (multiSpec) throw new ServiceException("该物料已启用多规格，请选择具体物料规格");
            return "";
        }
        var labels = jdbc.queryForList("""
            SELECT code || ' · ' || name FROM inv_material_variant
            WHERE variant_id=? AND material_id=? AND status='0' FOR SHARE
            """, String.class, variantId, materialId);
        if (!multiSpec || labels.isEmpty()) throw new ServiceException("物料规格已停用或不属于所选物料");
        return labels.getFirst();
    }

    /** 只接受物料允许使用的单位，并将固定或人工填写的系数保存为快照。 / Accept only material-enabled units and snapshot either the fixed or user-entered conversion factor. */
    private Map<String,Object> usageUnit(Long materialId,Long unitId,Map<String,Object> material,BigDecimal supplied) {
        if (unitId.toString().equals(material.get("unitId"))) return Map.of("name",material.get("unit"),"factor",BigDecimal.ONE);
        var configs = jdbc.queryForList("""
            SELECT u.unit_name AS name,a.conversion_mode AS mode,a.inventory_factor AS factor
            FROM inv_material_aux_unit a JOIN base_unit u ON u.unit_id=a.unit_id
            WHERE a.material_id=? AND a.unit_id=? AND a.usage_enabled
              AND u.status='0' AND u.del_flag='0'
            """,materialId,unitId);
        if (configs.isEmpty()) throw new ServiceException("请选择物料档案中允许生产使用的单位");
        var config = configs.getFirst();
        BigDecimal factor = "VARIABLE".equals(config.get("mode")) ? supplied : (BigDecimal) config.get("factor");
        if (factor!=null) factor = factor.stripTrailingZeros();
        if (factor==null || factor.signum()<=0 || factor.scale()>12 || factor.compareTo(new BigDecimal("1000000000"))>=0) {
            throw new ServiceException("请填写有效的单位换算系数（大于零、小于十亿，最多十二位小数）");
        }
        return Map.of("name",config.get("name"),"factor",factor);
    }
    /** 校验 BOM 物料颜色是否属于物料档案允许范围。 / Validate a BOM color against the material's configured color scope. */

    private String materialColor(Long materialId,Long colorId) {
        if (colorId==null) return "";
        var names = jdbc.queryForList("""
            SELECT c.color_name FROM inv_material_color m JOIN base_color c ON c.color_id=m.color_id
            WHERE m.material_id=? AND m.color_id=? AND c.status='0'
            """,String.class,materialId,colorId);
        if (names.isEmpty()) throw new ServiceException("请选择物料允许的颜色");
        return names.getFirst();
    }
    /** 重新校验已存规则的人员分类权限，阻止旧数据绕过当前授权。 / Recheck stored rules against current category access to prevent authorization bypass. */

    private void checkStoredScope(List<SavedRule> rules) {
        var checked = new HashSet<Long>();
        for (var saved : rules) {
            var rule = saved.rule();
            if (rule.childId()!=null) style(rule.childId());
            if (rule.materialId()!=null && checked.add(rule.materialId())) material(rule.materialId(),false);
        }
    }
    /** 读取 BOM 版本及其款式、制单人信息。 / Load a BOM version with its style and preparer metadata. */

    private Map<String,Object> version(Long id) {
        var rows = jdbc.queryForList("""
            SELECT id::text AS id,style_id::text AS "styleId",bom_code AS "bomCode",preparer_id::text AS "preparerId",version,status,remark,
                   rules::text AS rules,update_time::text AS revision,create_time::text AS "createTime",
                   release_time::text AS "releaseTime",
                   (SELECT nick_name FROM sys_user WHERE user_id=rd_style_bom.preparer_id) AS "creatorName",
                   (SELECT nick_name FROM sys_user WHERE user_id=rd_style_bom.update_by) AS "updaterName",
                   (SELECT nick_name FROM sys_user WHERE user_id=rd_style_bom.release_by) AS "releaserName"
            FROM rd_style_bom WHERE id=?
            """,id);
        if (rows.isEmpty()) throw new ServiceException("BOM 版本不存在");
        return rows.getFirst();
    }
    /** 将数据库规则快照解析为经过类型校验的 BOM 规则。 / Parse persisted snapshots into typed BOM rule objects. */

    private List<SavedRule> readRules(Map<String,Object> row) {
        return JsonUtils.parseArray(row.get("rules").toString(),SavedRule.class);
    }
    /** 组装 BOM 接口响应并补齐名称、单位及历史回显。 / Serialize BOM rules and hydrate labels, units and historical display values. */

    private List<Map<String,Object>> wireRules(List<SavedRule> saved) {
        return saved.stream().map(item -> {
            var rule = item.rule();
            Map<String,Object> row = new LinkedHashMap<>();
            row.put("childId",textId(rule.childId()));
            row.put("slot",rule.slot());
            row.put("slotId",positionId(rule).toString());
            row.put("usageType",rule.usageType());
            row.put("materialCategory",item.materialCategory());
            row.put("materialSpec",item.materialSpec());
            row.put("colorId",textId(rule.colorId()));
            row.put("sizeId",textId(rule.sizeId()));
            row.put("materialId",textId(rule.materialId()));
            row.put("materialVariantId",textId(rule.materialVariantId()));
            row.put("materialColorId",textId(rule.materialColorId()));
            row.put("usage",rule.usage()==null ? null : rule.usage().toPlainString());
            row.put("omitted",rule.omitted());
            row.put("remark",rule.remark());
            row.put("material",item.material());
            row.put("materialColor",item.materialColor());
            row.put("unit",item.unit());
            row.put("usageUnitId",rule.usageUnitId()==null ? item.unitId() : textId(rule.usageUnitId()));
            row.put("usageUnitName",item.usageUnitName()==null ? item.unit() : item.usageUnitName());
            row.put("conversionFactor",item.inventoryFactor()==null ? null : item.inventoryFactor().stripTrailingZeros().toPlainString());
            return row;
        }).toList();
    }

    /** 旧版本按原有分组生成稳定标识，无需改写已发布的快照。 / Derive stable identifiers from legacy rule groups without rewriting released snapshots. */
    private UUID positionId(Rule rule) {
        if (rule.slotId()!=null) return rule.slotId();
        return UUID.nameUUIDFromBytes((rule.childId()+":"+rule.slot().trim()).getBytes(StandardCharsets.UTF_8));
    }

    private String textId(Long id) { return id==null ? null : id.toString(); }

    private String field(String value,int max,String label) {
        String trimmed = Objects.toString(value,"").trim();
        if (trimmed.length()>max) throw new ServiceException(label+"最多"+max+"个字符");
        return trimmed;
    }
