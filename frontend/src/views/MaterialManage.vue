/** 在提交前定位缺项和重复规格，编码与名称按服务端口径忽略大小写。 / Locate missing and duplicate variant fields before submission. */
function validateVariants() {
  if (!form.value.multiSpec) return true
  const codes = new Map<string, number>()
  const names = new Map<string, number>()
  const report = (reason: string, index?: number) => {
    message.warning(reason)
    if (index === undefined) goToMaterialSection('variants')
    else document.getElementById('material-variant-' + index)?.scrollIntoView({ block: 'center', behavior: 'smooth' })
    return false
  }
  if (!form.value.variants.length) return report('已启用多规格，请至少添加一条规格')
  for (const [index, item] of form.value.variants.entries()) {
    const code = item.code.trim().toLowerCase()
    const name = item.name.trim().toLowerCase()
    const row = index + 1
    if (!code) return report('第 ' + row + ' 条规格缺少编码', index)
    if (!name) return report('第 ' + row + ' 条规格缺少名称', index)
    if (codes.has(code)) return report('第 ' + row + ' 条规格的编码与第 ' + codes.get(code) + ' 条重复', index)
    if (names.has(name)) return report('第 ' + row + ' 条规格的名称与第 ' + names.get(name) + ' 条重复', index)
    if (item.status === '0') {
      for (const field of variantAttributeFields.value) {
        const value = item.attributes?.[field.key]
        if (value == null || typeof value === 'string' && !value.trim()) {
          message.warning('规格「' + item.name + '」缺少' + specFieldLabel(field))
          document.getElementById('material-variant-attributes-' + index)?.scrollIntoView({ block: 'center', behavior: 'smooth' })
          return false
        }
      }
    }
    codes.set(code, row)
    names.set(name, row)
  }
  return true
}

