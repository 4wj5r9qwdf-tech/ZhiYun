type CategoryTreeNode = {
  value: string
  title: string
  pathLabel: string
  disabled: boolean
  children: CategoryTreeNode[]
}

// 按真实父级 ID 构树，授权路径中的祖先仍可展开。
// Build from parent IDs and keep path-only ancestors expandable.
function buildCategoryTree(source: Category[]): CategoryTreeNode[] {
  const nodes = new Map<string, CategoryTreeNode>()
  for (const category of source) {
    nodes.set(category.id, {
      value: category.id,
      title: `${category.name}（${category.code}）`,
      pathLabel: '',
      disabled: !category.selectable,
      children: [],
    })
  }

  const roots: CategoryTreeNode[] = []
  for (const category of source) {
    const node = nodes.get(category.id)!
    const parent = category.parentId ? nodes.get(category.parentId) : undefined
    if (parent) parent.children.push(node)
    else roots.push(node)
  }

  /** 为分类树节点生成完整祖先路径便于辨认。 / Build full ancestor paths so category-tree nodes are distinguishable. */
  function labelPaths(branch: CategoryTreeNode[], parentPath = '') {
    for (const node of branch) {
      node.pathLabel = parentPath ? `${parentPath} / ${node.title}` : node.title
      labelPaths(node.children, node.pathLabel)
    }
  }
  labelPaths(roots)
  return roots
}

