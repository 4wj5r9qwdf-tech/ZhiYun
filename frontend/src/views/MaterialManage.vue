/** 将导入行解析成物料字段并逐行校验。 / Parse imported rows into material fields and validate them individually. */
function parseImport(fields: string[]) {
  const [code,name,schemeCode,categoryCode,_legacySpecification,model,brand,materialDesc,unitCode,colorCodes,
    sort,remark,fabricWeightGsm,fabricWidthCm,composition,auxiliaryCodes,specTemplateCode,specJson,materialUnitsJson] = fields.map(value => value.trim())
  const sortOrder = sort ? Number(sort) : 0
  if (!name || !schemeCode || !categoryCode || !unitCode) throw new Error('物料名称、分类类型编码、分类编码和库存单位编码必填')
  if (!Number.isInteger(sortOrder) || sortOrder < 0 || sortOrder > 999999) throw new Error('排序须为0到999999之间的整数')
  let specValues: unknown = {}
  if (specJson) {
    try { specValues = JSON.parse(specJson) }
    catch { throw new Error('模板规格值格式无效，请参考导出文件') }
    if (!specValues || typeof specValues !== 'object' || Array.isArray(specValues)) {
      throw new Error('模板规格值须为字段对象')
    }
  }
  return { code,name,schemeCode,categoryCode,model,brand,materialDesc,unitCode,colorCodes,
    sortOrder,remark,fabricWeightGsm,fabricWidthCm,composition,auxiliaryCodes,specTemplateCode,specValues,materialUnitsJson }
}

/** 解析多值编码单元格，去重并保留输入顺序。 / Parse a multi-code cell, deduplicate values and preserve their order. */
function splitCodes(value: string) {
  return (value || '').split(/[，,]/).map(code => code.trim()).filter(Boolean)
}

/** 复用物料新增校验逐条导入并返回行级结果。 / Import rows through the standard material validation path and return per-row results. */
async function importMaterial(payload: ReturnType<typeof parseImport> | Record<string, any>) {
  const category = categories.value.find(item => item.schemeCode === payload.schemeCode &&
    item.code === payload.categoryCode && item.selectable)
  const unit = units.value.find(item => item.code === payload.unitCode && !item.baseUnitId && item.selectable)
  if (!category) throw new Error(`分类类型/分类编码不存在或无权限：${payload.schemeCode}/${payload.categoryCode}`)
  if (!unit) throw new Error(`库存单位不可用：${payload.unitCode}`)
  const colorIds = splitCodes(payload.colorCodes).map(code => {
    const color = colors.value.find(item => item.code === code && item.selectable)
    if (!color) throw new Error(`颜色编码不存在或已停用：${code}`)
    return color.id
  })
  const auxiliaryUnitIds = (payload.materialUnitsJson ? [] : splitCodes(payload.auxiliaryCodes)).map(code => {
    const auxiliary = units.value.find(item => item.code === code && item.baseUnitId === unit.id && item.selectable)
    if (!auxiliary) throw new Error(`辅助单位不可用或不属于所选库存单位：${code}`)
    return auxiliary.id
  })
  let materialUnits: MaterialUnit[] | undefined
  if (payload.materialUnitsJson) {
    let parsed: any
    try { parsed = JSON.parse(payload.materialUnitsJson) } catch { throw new Error('物料单位配置格式无效，请参考导出文件') }
    if (!Array.isArray(parsed)) throw new Error('物料单位配置必须是数组')
    materialUnits = parsed.map((item: any) => {
      const selected = units.value.find(entry => entry.code === item.unitCode && entry.selectable)
      const reference = item.referenceUnitCode ? units.value.find(entry => entry.code === item.referenceUnitCode && entry.selectable) : undefined
      if (!selected || (item.mode === 'FIXED' && !reference)) throw new Error('物料单位配置中的单位编码不可用')
      return { unitId: selected.id, mode: item.mode, referenceUnitId: reference?.id, factor: item.factor ?? '', purchase: item.purchase, usage: item.usage }
    })
  }
  const { schemeCode, categoryCode, unitCode, colorCodes, auxiliaryCodes, materialUnitsJson, ...fields } = payload
  const res: any = await api.post('/inventory/material', {
    ...fields, categoryId: category.id, inventoryUnitId: unit.id, colorIds, auxiliaryUnitIds, ...(materialUnits ? { materialUnits } : {}),
  })
  if (res.code !== 200) throw new Error(res.msg || '导入失败')
}

/** 将模板属性与各物料规格属性展开为可读导出字段。 / Flatten template and variant attributes into readable export columns. */
function exportSpecValues(row: Material) {
  const template = specTemplates.value.find(item => item.code === row.specTemplateCode)
  const entries = (template?.fields ?? [])
    .filter(field => !isLegacySpecKey(field.key) && row.specValues?.[field.key] != null)
    .map(field => [field.key, row.specValues[field.key]])
  return entries.length ? JSON.stringify(Object.fromEntries(entries)) : ''
}

