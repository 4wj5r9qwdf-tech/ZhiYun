    return { id: item.unitId, unit, uses, conversion }
  })
}

/** 默认类型用于列表与新增的起始范围，保留用户手动选择。 */
async function loadDefaultCategory() {
  try {
    const response: any = await api.get('/inventory/material/default-category')
    if (response.code !== 200) throw new Error(response.msg)
    const id = String(response.data?.schemeId || '')
    const next = categories.value.some(row => row.schemeId === id && row.selectable) ? id : undefined
    categoryScopeUnavailable.value = Boolean(response.data?.invalid || (id && !next))
    if (!defaultResolved || defaultSchemeId.value !== next) {
      visibleSchemeId.value = next
      schemeFilter.value = next
      categoryFilter.value = undefined
    }
    if (response.data?.invalid && (!defaultResolved || defaultSchemeId.value !== next)) {
      message.warning('物料配置的分类类型当前不可用，请联系管理员核对参数或权限。')
    }
    defaultSchemeId.value = next
    defaultResolved = true
  } catch {
    if (!defaultResolved) message.warning('物料分类参数读取失败，请重新查询。')
  }
}
