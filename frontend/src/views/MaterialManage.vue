  return (row.materialUnits || []).map(item => {
    const unit = units.value.find(unit => unit.id === item.unitId)?.name || item.unitId || '—'
    const reference = units.value.find(unit => unit.id === item.referenceUnitId)?.name || item.referenceUnitId || row.inventoryUnitName
