/** 用模板名称及单位展示属性，保留布尔值和零值。 / Format stored attributes without dropping false or zero. */
function attributeLines(row: Material, values: Record<string, SpecValue>, perVariant: boolean) {
  const template = specTemplates.value.find(item => item.code === row.specTemplateCode)
  return (template?.fields || []).flatMap(field => {
    if (Boolean(row.variantFields?.includes(field.key)) !== perVariant) return []
    const value = !perVariant && isLegacySpecKey(field.key) ? row[field.key] : values[field.key]
    if (value == null || value === '') return []
    return [field.label + '：' + (typeof value === 'boolean' ? (value ? '是' : '否') : value) + (field.unit ? ' ' + field.unit : '')]
  })
}

/** 展示档案配置的单位与用途，保留实际数量模式。 / Describe configured units and their conversion modes. */
