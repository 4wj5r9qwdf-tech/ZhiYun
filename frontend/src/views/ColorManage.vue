<script setup lang="ts">
/** 全局颜色基础资料：供物料、款式等业务复用；停用项保留供历史显示。 / Shared color master for material and style workflows. */
import '../assets/standard-list-fill.css'
import { computed, onMounted, ref } from 'vue'
import message from 'ant-design-vue/es/message'
import Modal from 'ant-design-vue/es/modal'
import { PlusOutlined, SearchOutlined, UploadOutlined, DownloadOutlined } from '@ant-design/icons-vue'
import api from '../api'
import StandardListLayout from '../components/StandardListLayout.vue'
import FoundationTable from '../components/FoundationTable.vue'
import FoundationImport from '../components/FoundationImport.vue'
import { createSavedFormDefaults } from '../utils/savedFormDefaults'
import { encodeCsv } from '../utils/csv'
import { downloadFoundationFile } from '../utils/foundation'
import { can } from '../utils/perms'

type ColorRow = { id: string; code: string; name: string; color_value: string; sort_order: number; status: string; remark: string }
type ColorForm = { id?: string; code: string; autoGeneratedCode: string; name: string; color_value: string; sort_order: number; remark: string }
const blankForm = (): ColorForm => ({ code: '', autoGeneratedCode: '', name: '', color_value: '', sort_order: 0, remark: '' })
const rows = ref<ColorRow[]>([])
const loading = ref(false)
const keyword = ref('')
const status = ref<string>()
const showDialog = ref(false)
const isEdit = ref(false)
const saving = ref(false)
const importOpen = ref(false)
const form = ref<ColorForm>(blankForm())
const initialForm = ref('')
const savedDefaults = createSavedFormDefaults(localStorage, `color_saved_form:${localStorage.getItem('userId') || 'anon'}`, blankForm, ['id', 'code', 'autoGeneratedCode'])
const canAdd = computed(() => can('system:color:add'))
const canEdit = computed(() => can('system:color:edit'))
const canRemove = computed(() => can('system:color:remove'))
const filteredRows = computed(() => {
  const q = keyword.value.trim().toLocaleLowerCase()
  return rows.value.filter(row => (!q || `${row.code} ${row.name} ${row.color_value} ${row.remark}`.toLocaleLowerCase().includes(q)) && (!status.value || row.status === status.value))
})
const columns = [
  { key: 'code', title: '颜色编码', width: 120 },
  { key: 'name', title: '颜色名称', width: 120 },
  { key: 'color_value', title: '色样', width: 120 },
  { key: 'sort_order', title: '排序', width: 90, numeric: true },
  { key: 'status', title: '状态', width: 100 },
  { key: 'remark', title: '备注', width: 160 },
]

/** 加载管理目录完整集合，前端统一筛选分页。 / Load the full small master-data set for local filtering and paging. */
async function load() {
  loading.value = true
  try {
    const res: any = await api.get('/system/color/list')
    if (res.code !== 200) throw new Error(res.msg || '颜色目录加载失败')
    rows.value = (res.data || []).map((row: any) => ({ ...row, id: String(row.id), sort_order: Number(row.sort_order || 0) }))
  } catch (error: any) { message.error(error?.response?.data?.msg || error?.message || '颜色目录加载失败') }
  finally { loading.value = false }
}

/** 读取可编辑编码建议，实际分配由新增接口重新校验。 / Fetch an editable code suggestion; the create endpoint reallocates safely. */
async function nextCode() {
  const res: any = await api.get('/system/color/next-code')
  if (res.code !== 200) throw new Error(res.msg || '颜色编码建议获取失败')
  return String(res.data?.code || '')
}

/** 普通新增保持空白，仅保存并新增时恢复上次成功表单。 / Restore prior defaults only for the explicit save-and-add flow. */
async function openAdd(usePrevious = false) {
  try {
    isEdit.value = false
    const next = blankForm()
    if (usePrevious) Object.assign(next, savedDefaults.load())
    next.code = await nextCode()
    next.autoGeneratedCode = next.code
    form.value = next
    initialForm.value = JSON.stringify(form.value)
    showDialog.value = true
  } catch (error: any) { message.error(error?.response?.data?.msg || error?.message || '打开新增窗口失败') }
}

/** 编辑既有颜色时固定稳定编码，只允许维护展示字段。 / Keep the stable code immutable while editing display fields. */
function openEdit(row: ColorRow) {
  isEdit.value = true
  form.value = { ...row, autoGeneratedCode: '' }
  initialForm.value = JSON.stringify(form.value)
  showDialog.value = true
}

/** 关闭前保护未保存输入，避免误触丢失颜色资料。 / Confirm before discarding unsaved color data. */
function closeForm() {
  if (saving.value) return
  if (JSON.stringify(form.value) === initialForm.value) { showDialog.value = false; return }
  Modal.confirm({ title: '放弃未保存的修改？', content: '关闭后，本次输入不会保存。', okText: '放弃修改', cancelText: '继续编辑', onOk: () => { showDialog.value = false } })
}

/** 保存单条颜色，并仅在显式连续新增时保存默认值。 / Persist one color and retain defaults only for save-and-add. */
function saveColor(andAdd: boolean) {
  if (saving.value) return
  const name = form.value.name.trim()
  const code = form.value.code.trim()
  if (!code) { message.warning('请填写颜色编码'); return }
  if (!name) { message.warning('请填写颜色名称'); return }
  if (form.value.color_value && !/^#[0-9a-fA-F]{6}$/.test(form.value.color_value)) { message.warning('色值格式应为 #RRGGBB，例如 #1E5EFF'); return }
  saving.value = true
  const payload = { code, autoGeneratedCode: form.value.autoGeneratedCode, name, color_value: form.value.color_value.toUpperCase(), sort_order: form.value.sort_order, remark: form.value.remark.trim() }
  const request = isEdit.value ? api.put(`/system/color/${form.value.id}`, payload) : api.post('/system/color', payload)
  request.then(async (res: any) => {
    if (res.code !== 200) throw new Error(res.msg || '保存失败')
    message.success(isEdit.value ? '颜色已保存' : '颜色已新增')
    await load()
    if (andAdd && !isEdit.value) {
      savedDefaults.save(payload)
      await openAdd(true)
    } else showDialog.value = false
  }).catch((error: any) => message.error(error?.response?.data?.msg || error?.message || '保存失败')).finally(() => { saving.value = false })
}

/** 状态列启停先确认，再由后端校验权限并写业务审计。 / Confirm status changes before the authorized audited update. */
function toggleStatus(row: ColorRow) {
  const next = row.status === '0' ? '1' : '0'
  Modal.confirm({
    title: next === '0' ? '启用颜色' : '停用颜色',
    content: next === '0' ? `确认启用“${row.name}（${row.code}）”吗？` : `确认停用“${row.name}（${row.code}）”吗？停用后不可用于新的物料选择，历史引用仍会保留。`,
    okText: '确认', cancelText: '取消',
    onOk: async () => {
      const res: any = await api.put(`/system/color/${row.id}/status`, { status: next })
      if (res.code !== 200) throw new Error(res.msg || '状态更新失败')
      message.success(next === '0' ? '已启用' : '已停用')
      await load()
    },
  })
}

/** 删除前说明外键限制；已被引用的数据只能停用。 / Explain reference protection before physical deletion. */
function remove(row: ColorRow) {
  Modal.confirm({
    title: '删除颜色', content: `确认删除“${row.name}（${row.code}）”吗？已被物料或业务记录引用的颜色不能删除，可停用。`,
    okText: '确认删除', cancelText: '取消', okButtonProps: { danger: true },
    onOk: async () => {
      const res: any = await api.delete(`/system/color/${row.id}`)
      if (res.code !== 200) throw new Error(res.msg || '删除失败')
      message.success('颜色已删除')
      await load()
    },
  })
}

const importHeaders = ['颜色编码', '颜色名称', '色值', '排序', '备注']
/** 解析导入行并在前端检查色值及排序格式。 / Parse CSV rows and validate the swatch and sort value. */
function parseImport(fields: string[]) {
  const [code, name, color_value, sort, remark] = fields.map(value => value.trim())
  if (color_value && !/^#[0-9a-fA-F]{6}$/.test(color_value)) throw new Error('色值应为 #RRGGBB 格式')
  const sort_order = sort ? Number(sort) : 0
  if (!Number.isInteger(sort_order) || sort_order < 0 || sort_order > 999999) throw new Error('排序须为0到999999之间的整数')
  return { code, name, color_value: color_value.toUpperCase(), sort_order, remark }
}
/** 导入复用单条新增接口，确保权限、唯一性和审计口径一致。 / Reuse create so imports share authorization, uniqueness, and audit behavior. */
async function importColor(payload: Record<string, any>) {
  const res: any = await api.post('/system/color', payload)
  if (res.code !== 200) throw new Error(res.msg || '导入失败')
}
/** 导出当前筛选结果，便于修订后批量导入。 / Export the currently filtered rows for review and re-import. */
function exportCsv() {
  const content = encodeCsv([importHeaders, ...filteredRows.value.map(row => [row.code, row.name, row.color_value, String(row.sort_order), row.remark])])
  downloadFoundationFile('颜色目录.csv', content)
}

onMounted(load)
</script>

<template>
  <StandardListLayout>
    <template #filters>
      <label class="zy-filter-field"><span>关键词</span><a-input v-model:value="keyword" allow-clear placeholder="搜索颜色编码、名称或色值" style="width:300px" @press-enter="load" /></label>
      <label class="zy-filter-field"><span>状态</span><a-select v-model:value="status" allow-clear placeholder="全部状态" style="width:140px"><a-select-option value="0">启用</a-select-option><a-select-option value="1">停用</a-select-option></a-select></label>
      <a-button type="primary" :loading="loading" @click="load"><template #icon><SearchOutlined /></template>查询</a-button>
      <a-button @click="keyword='';status=undefined;load()">重置</a-button>
    </template>
    <template #default>
      <FoundationTable storage-key="color_list_v2" :columns="columns" :rows="filteredRows" :loading="loading" :action-width="120">
        <template #actions>
          <a-button v-if="canAdd" type="primary" @click="openAdd()"><template #icon><PlusOutlined /></template>新增</a-button>
          <a-button v-if="canAdd" @click="importOpen=true"><template #icon><UploadOutlined /></template>导入</a-button>
          <a-button @click="exportCsv"><template #icon><DownloadOutlined /></template>导出</a-button>
        </template>
        <template #cell="{ column, row }">
          <template v-if="column.key==='color_value'"><span v-if="row.color_value" class="color-swatch" :style="{ backgroundColor: row.color_value }" /><span>{{ row.color_value || '未设置色值' }}</span></template>
          <template v-else-if="column.key==='status'"><a-switch :checked="row.status==='0'" :disabled="!canEdit" checked-children="启用" un-checked-children="停用" @change="toggleStatus(row)" /></template>
          <template v-else>{{ row[String(column.key)] ?? '—' }}</template>
        </template>
        <template #action="{ row }">
          <a-space :size="6"><a-button v-if="canEdit" type="primary" size="small" @click="openEdit(row)">编辑</a-button><a-button v-if="canRemove" danger size="small" @click="remove(row)">删除</a-button></a-space>
        </template>
      </FoundationTable>
    </template>
  </StandardListLayout>

  <a-modal :open="showDialog" :title="isEdit?'编辑颜色':'新增颜色'" :width="620" :mask-closable="false" :keyboard="false" :closable="!saving" @cancel="closeForm">
    <a-form layout="vertical">
      <a-form-item label="颜色编码" required><a-input v-model:value="form.code" :disabled="isEdit" :maxlength="40" placeholder="自动生成建议值，可自行修改" /><div class="field-help">编码创建后固定；自动生成值可在保存前修改。</div></a-form-item>
      <a-form-item label="颜色名称" required><a-input v-model:value="form.name" :maxlength="80" placeholder="例如：藏青" /></a-form-item>
      <a-form-item label="色样 / 色值"><div class="color-input"><input v-model="form.color_value" type="color" aria-label="选择色样" /><a-input v-model:value="form.color_value" :maxlength="7" placeholder="#1E5EFF" /><span v-if="form.color_value" class="color-swatch large" :style="{ backgroundColor: form.color_value }" /></div><div class="field-help">可选；填写六位十六进制色值。屏幕色样仅辅助辨认，不能替代实物色卡或供应商色号。</div></a-form-item>
      <a-form-item label="排序"><a-input-number v-model:value="form.sort_order" :min="0" :max="999999" :precision="0" style="width:100%" /></a-form-item>
      <a-form-item label="备注"><a-textarea v-model:value="form.remark" :maxlength="500" :rows="3" show-count /></a-form-item>
    </a-form>
    <template #footer>
      <a-button :disabled="saving" @click="closeForm">取消</a-button>
      <a-button type="primary" :loading="saving" @click="saveColor(false)">保存</a-button>
      <a-button v-if="!isEdit && canAdd" type="primary" ghost :loading="saving" @click="saveColor(true)">保存并新增</a-button>
    </template>
  </a-modal>
  <FoundationImport v-model:open="importOpen" title="颜色导入" :headers="importHeaders" help="颜色编码和名称必填；色值可留空，填写时使用 #RRGGBB 格式；状态由系统默认启用。导入逐行保存，失败行可下载修正后重试。" :parse="parseImport" :submit="importColor" :duplicate-key="(payload:any)=>payload.code.trim().toLowerCase()" @done="load" />
</template>

